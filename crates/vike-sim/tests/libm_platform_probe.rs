//! The cross-platform PIN for this crate's transcendental sites — the simulator half of what was
//! one probe while the simulator lived inside `vike-backtest`. It was SPLIT when the simulator left
//! that crate (docs/decisions/0087): the two sites that decide a FILL came here with their code, and
//! `crates/vike-backtest/tests/libm_platform_probe.rs` keeps the ranking site (`objective.rs`) and
//! the harness's own source walk. The corpora, the hasher and the recorded hashes moved verbatim —
//! every row folds its own seeded corpus, so a row hashes identically whichever file holds it.
//!
//! IEEE 754 requires `+ - * /` and `sqrt` to be correctly rounded and requires NOTHING of
//! `ln`/`exp`/`pow`/`cos`, so an `f64` METHOD call reaches whichever libm the PLATFORM ships —
//! MSVC's CRT on the Windows dev box, glibc on the the CI box Linux boxes and every CI runner — and the
//! two disagree in the last bit. `crates/vike-sim/Cargo.toml`'s `libm` line names the two sites this
//! crate converted for that reason, and
//! `docs/decisions/0032-transcendentals-come-from-the-libm-crate-not-the-platform.md` is the
//! accepted verdict.
//!
//! # What each pinned row actually decides — read this before ranking a red row as cosmetic
//!
//! * [`PLATFORM_INVARIANT`]'s `impact::AlmgrenChriss::impact_frac` is a **FILL PRICE**. Its result
//!   is ADDED to the engine's flat slippage and multiplied into the executed price
//!   (`crates/vike-fills/src/broker_sim.rs`'s `adverse_fill_price`, reached through
//!   `crates/vike-sim/src/engine/sim_broker.rs`'s `SimBroker::slippage_for`), so it lands on the
//!   equity curve of every bar-mode backtest that opts the model in. It is also the worst case under
//!   0032's classify-a-power-by-its-BASE rule: base AND exponent are arbitrary runtime `f64`s
//!   (`AC_ALPHA = 0.891`, `AC_BETA = 0.600`).
//! * `queue_model::ProbQueueModel` decides **WHETHER A RESTING ORDER FILLS**.
//!   `crates/vike-sim/src/queue_model.rs`'s `ProbFunc` — its `f` weights the front-vs-back
//!   attribution of a depth decrease, so it moves the estimated queue ahead of a resting maker —
//!   a backtest can fill on one box and not on the other.
//!
//! `.sqrt()` calls are not covered and need no coverage: IEEE 754 requires `sqrt` correctly
//! rounded, so it is already identical on every box.
//!
//! # ⚠ The corpus is PURE ARITHMETIC, and that is load-bearing
//!
//! Every input is generated by an integer LCG plus `+ - * /`, never by `.sin()`/`.cos()`. Those are
//! themselves platform-dependent (MEASURED — `crates/vike-analytics/tests/libm_platform_probe.rs`'s
//! Part A sweeps them as its control), so generating inputs with them would make every row below
//! diverge because of the INPUTS rather than because of the function under test: a false positive
//! that reads exactly like a real one.
//!
//! ```text
//! <cargo> test -p vike-sim --test libm_platform_probe
//! ```

use vike_model::libm_walk::{banned_needles, cfg_test_ranges};
use vike_sim::{AlmgrenChriss, ImpactInputs, ImpactModel, ProbQueueModel, QueueModel};

// =================================================================================================
// The hashing/corpus machinery, deliberately a per-crate COPY. Decision 0074 moved the TEXT parser
// the SOURCE half below walks with — and ONLY the text parser — into `vike_model::libm_walk`; the
// hasher and the corpus stay beside the table they pin.
// =================================================================================================

/// FNV-1a over `f64::to_bits`, NaN canonicalised so a NaN's sign and payload — neither of which the
/// architecture pins — cannot report a divergence that is not one. The same hasher the sibling
/// probes use, so a row moved between crates hashes identically (which is what let the rows below
/// move here from `vike-backtest` without re-recording).
struct Fnv(u64);

impl Fnv {
    fn new() -> Self {
        Fnv(0xcbf2_9ce4_8422_2325)
    }
    fn push(&mut self, v: f64) {
        let bits = if v.is_nan() { 0x7ff8_0000_0000_0000u64 } else { v.to_bits() };
        for b in bits.to_le_bytes() {
            self.0 ^= u64::from(b);
            self.0 = self.0.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
    fn hex(&self) -> String {
        format!("{:016x}", self.0)
    }
}

/// Deterministic pseudo-random `f64` in `(0, 1)` from a pure-integer LCG.
///
/// ⚠ No transcendental anywhere in here, for the reason the module doc gives. The `as f64` of a
/// 53-bit integer is exact and the single division is correctly rounded, so the corpus is
/// bit-identical on every platform BY CONSTRUCTION — which is what makes a divergence in the
/// OUTPUT attributable to the function under test rather than to the inputs.
fn lcg(seed: &mut u64) -> f64 {
    *seed = seed.wrapping_mul(6_364_136_223_846_793_005).wrapping_add(1_442_695_040_888_963_407);
    ((*seed >> 11) as f64) / ((1u64 << 53) as f64)
}

/// Samples per row. Large enough that a last-bit disagreement on a rare input survives into the
/// hash rather than being rounded away — the trap the indicators twin fell into twice with a single
/// series, where two genuinely divergent indicators both reported "identical".
const SAMPLES: usize = 4096;

/// One row's verdict over its own corpus.
struct Row {
    label: &'static str,
    hash: String,
    /// How many samples were folded in.
    n: usize,
    /// ⚠ NON-VACUITY GUARD. A row whose corpus collapses to one value — or to all-NaN — hashes
    /// identically on every platform and reads as a PASS while pinning nothing. This is how many
    /// DISTINCT FINITE values the samples took, so a row reporting `distinct=1` is worthless
    /// rather than reassuring. The analytics twin caught a real instance of exactly that
    /// (`overfit::pbo_cscv`), which is why this is a field on EVERY row rather than a check
    /// hand-applied to a chosen few.
    distinct: usize,
}

fn finish(label: &'static str, vals: &[f64]) -> Row {
    let mut h = Fnv::new();
    for &v in vals {
        h.push(v);
    }
    let mut bits: Vec<u64> = vals.iter().filter(|v| v.is_finite()).map(|v| v.to_bits()).collect();
    bits.sort_unstable();
    bits.dedup();
    Row { label, hash: h.hex(), n: vals.len(), distinct: bits.len() }
}

/// Smallest number of DISTINCT finite values a row may carry before its pin is treated as vacuous.
const MIN_DISTINCT: usize = 64;

