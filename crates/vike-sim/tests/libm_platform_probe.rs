/// Every covered function, folded over its own corpus.
///
/// Returns rows in a FIXED order; [`PLATFORM_INVARIANT`] is compared positionally, so a reordering
/// is a re-record rather than a silent re-pairing.
fn production_rows() -> Vec<Row> {
    let mut out = Vec::new();

    // --- impact::AlmgrenChriss::impact_frac — `libm::pow(nu * T, alpha)` + `libm::pow(nu, beta)`
    //
    // The published calibration is swept ALONGSIDE randomised coefficient sets rather than alone:
    // `AlmgrenChriss`'s fields are all `pub`, a profile can set any of them, and a site that is
    // portable only at its default parameters is portable by accident. `exec_time` is swept too —
    // it is the one input reaching BOTH `pow` calls (it builds `nu`, and it multiplies back into
    // the permanent term's base).
    {
        let mut s = 0x1234_5678_9abc_def0u64;
        let mut vals = Vec::with_capacity(SAMPLES);
        for i in 0..SAMPLES {
            // Alternate the published calibration with a randomised one, so the row covers the
            // configuration that actually ships AND the space around it.
            let model = if i % 2 == 0 {
                AlmgrenChriss::with_exec_time(0.25 + lcg(&mut s) * 4.0)
            } else {
                AlmgrenChriss {
                    gamma: 0.05 + lcg(&mut s) * 1.0,
                    alpha: 0.30 + lcg(&mut s) * 1.4,
                    eta: 0.02 + lcg(&mut s) * 0.6,
                    beta: 0.20 + lcg(&mut s) * 1.2,
                    exec_time: 0.25 + lcg(&mut s) * 4.0,
                }
            };
            let input = ImpactInputs {
                qty: 1.0 + lcg(&mut s) * 250_000.0,
                avg_volume: 1_000.0 + lcg(&mut s) * 5_000_000.0,
                sigma: 1e-4 + lcg(&mut s) * 0.12,
            };
            vals.push(model.impact_frac(&input));
        }
        out.push(finish("impact::AlmgrenChriss::impact_frac (pow x2)", &vals));
    }

    // --- queue_model::ProbQueueModel — `ProbFunc::f` through the PUBLIC trait verb.
    //
    // ⚠ `ProbFunc::f` is a PRIVATE method and is deliberately not made reachable in order to pin
    // it: the consumer that matters is `on_depth_change`, and driving `f` through the verb the
    // tick-replay engine actually calls is the STRONGER pin — it covers the attribution arithmetic
    // wrapped around the call as well. `st.front_qty` after the fold IS the estimated queue ahead
    // of the order, i.e. the quantity a fill decision reads.
    //
    // Two rows, because the two arms are two different libm calls and one of them has a parameter.
    // `Log` is `libm::log(1 + x)` unconditionally. `Power(n)` is `libm::pow(x, n)`, which returns
    // `x` EXACTLY at the default `n = 1` (libm's `pow` takes a `y is ±1` branch ahead of any
    // arithmetic — the site's own doc says so), and is a real transcendental at every other
    // exponent. The `Power` row therefore sweeps `n` AWAY from 1: pinning `n = 1` would pin the one
    // value at which the site is portable by accident.
    {
        let mut s = 0x0fed_cba9_8765_4321u64;
        let m = ProbQueueModel::log();
        let mut vals = Vec::with_capacity(SAMPLES);
        for _ in 0..SAMPLES {
            let level = 10.0 + lcg(&mut s) * 50_000.0;
            let mut st = m.on_new_order(level);
            // A trade FIRST, so `cum_trade_qty` is non-zero and the `chg_net` netting is exercised
            // rather than short-circuited.
            m.on_trade(&mut st, lcg(&mut s) * level * 0.4);
            let new_qty = level * (0.05 + lcg(&mut s) * 0.9);
            m.on_depth_change(&mut st, level, new_qty);
            vals.push(st.front_qty);
        }
        out.push(finish("queue_model::ProbQueueModel::log (log)", &vals));
    }
    {
        let mut s = 0x2222_3333_4444_5555u64;
        let mut vals = Vec::with_capacity(SAMPLES);
        for _ in 0..SAMPLES {
            // n strictly away from 1.0 — see the note above.
            let n = 1.15 + lcg(&mut s) * 2.5;
            let m = ProbQueueModel::power(n);
            let level = 10.0 + lcg(&mut s) * 50_000.0;
            let mut st = m.on_new_order(level);
            m.on_trade(&mut st, lcg(&mut s) * level * 0.4);
            let new_qty = level * (0.05 + lcg(&mut s) * 0.9);
            m.on_depth_change(&mut st, level, new_qty);
            vals.push(st.front_qty);
        }
        out.push(finish("queue_model::ProbQueueModel::power (pow)", &vals));
    }

    out
}

/// ⚠ **ONE set of constants for EVERY platform — that is the entire claim.**
///
/// These three rows were recorded in `crates/vike-backtest/tests/libm_platform_probe.rs` on both
/// platforms and MOVED here with the code they pin, hashes unchanged: each row folds its own seeded
/// corpus, so nothing about a row depends on which file (or which other rows) surround it.
///
/// ⚠ **Re-record by RUNNING, never by editing a digit**, and never from ONE box. If a row goes red
/// the question is which platform moved and why:
///   (a) an intended numeric change — re-record on both boxes and pin the hash they AGREE on; or
///   (b) a call site went back to the platform's libm, in which case the two boxes will NOT agree
///       and the fix is in the source, not here.
///
/// ⚠ **A per-platform table (`#[cfg(windows)]` / `#[cfg(unix)]`) is NOT a repair and must never be
/// added.** It would make the gate green by asserting the divergence was intended — the one
/// conclusion this whole exercise refutes.
const PLATFORM_INVARIANT: [(&str, &str); 3] = [
    ("impact::AlmgrenChriss::impact_frac (pow x2)", "a42b7a7410b0b803"),
    ("queue_model::ProbQueueModel::log (log)", "2b16a2b6cc394c1a"),
    ("queue_model::ProbQueueModel::power (pow)", "c5a36e38ac3cdc04"),
];

/// The cross-platform proof, as a GATE rather than a diff somebody has to remember to run.
///
/// NOT `#[ignore]`d: CI runs it on Linux every PR and `just t vike-sim` runs it on the Windows dev
/// box, both against the same committed table — so the two platforms are held equal without anyone
/// diffing two terminal windows.
#[test]
fn converted_functions_are_platform_invariant() {
    let got = production_rows();
    let want = &PLATFORM_INVARIANT;
    let table = "PLATFORM_INVARIANT";
    assert_eq!(got.len(), want.len(), "row count drifted from {table} — it must be re-recorded");

    let mut bad = Vec::new();
    for (r, (want_label, want_hash)) in got.iter().zip(want.iter()) {
        assert_eq!(
            &r.label, want_label,
            "row ORDER drifted from {table} — the compare is positional"
        );
        if r.hash != *want_hash {
            bad.push(format!("  {:<48} want={want_hash} got={}", r.label, r.hash));
        }
    }

    // The non-vacuity half is asserted BEFORE the hashes, deliberately: a thin row is a defect
    // whether or not its hash matched, and an author re-recording a row must be told about it
    // BEFORE pasting a hash that would pin nothing.
    let thin: Vec<String> = got
        .iter()
        .filter(|r| r.distinct < MIN_DISTINCT)
        .map(|r| format!("  {:<48} {} distinct finite of {} samples", r.label, r.distinct, r.n))
        .collect();
    assert!(
        thin.is_empty(),
        "a pinned row's corpus is too thin to detect a last-bit divergence: it would hash \
         identically on every platform and read as a PASS while proving nothing. WIDEN the input \
         ranges — never lower MIN_DISTINCT ({MIN_DISTINCT}):\n{}",
        thin.join("\n")
    );

    if !bad.is_empty() {
        let paste: String =
            got.iter().map(|r| format!("    (\"{}\", \"{}\"),\n", r.label, r.hash)).collect();
        panic!(
            "\nvike-sim output moved away from {table}:\n{}\n\n\
             There is no tolerance here to widen, and hand-editing a digit defeats the gate.\n\
             Establish WHY before re-recording:\n\
               (a) an intended numeric change — re-record on BOTH boxes and pin the agreed hash; or\n\
               (b) a call site changed which libm it reaches, in which case the two platforms will\n\
                   NOT agree and the fix is in the source, not here.\n\n\
             const {table}: [(&str, &str); {}] = [\n{paste}];\n",
            bad.join("\n"),
            got.len(),
        );
    }
}

/// The control arm for the non-vacuity threshold itself.
///
/// ⚠ Without this, `MIN_DISTINCT` is an assertion nobody has checked DISCRIMINATES. A `distinct`
/// computation that counted samples rather than distinct values — or a threshold accidentally set
/// to `0` — would pass every row above while the guard did nothing, and catching a check that
/// passes while doing nothing is the guard's entire job.
#[test]
fn the_non_vacuity_check_discriminates() {
    let constant: Vec<f64> = (0..SAMPLES).map(|_| 0.5f64).collect();
    let r = finish("control::constant", &constant);
    assert!(
        r.distinct < MIN_DISTINCT,
        "the non-vacuity check does not discriminate: a constant series reported {} distinct",
        r.distinct
    );
    let nans: Vec<f64> = (0..SAMPLES).map(|_| f64::NAN).collect();
    assert_eq!(
        finish("control::nan", &nans).distinct,
        0,
        "an all-NaN row must report ZERO distinct FINITE values — the analytics twin's vacuous row \
         was all-NaN rather than constant, and a `distinct` that counted NaNs would have passed it"
    );
    let mut s = 0xdead_beef_cafe_babeu64;
    let rich: Vec<f64> = (0..SAMPLES).map(|_| lcg(&mut s)).collect();
    assert!(
        finish("control::rich", &rich).distinct >= MIN_DISTINCT,
        "the corpus generator itself is degenerate — every row above is void"
    );
}

