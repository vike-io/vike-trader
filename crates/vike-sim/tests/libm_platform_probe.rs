/// Production code in this crate must reach a transcendental through the `libm` CRATE.
///
/// ⚠ Not redundant with the hash table. That pins THREE functions; this crate carries a dozen
/// source files, and a new call site in any of the others — `engine.rs` and `sim_broker.rs` are
/// the fill engine itself — would be invisible to every corpus above while quietly making a fill
/// price depend on which box ran the replay.
///
/// Scope: every `.rs` under `src/`, recursively, MINUS each file's `#[cfg(test)]` item ranges. The
/// text machinery it walks with — `banned_needles` and `cfg_test_ranges`, from
/// `vike_model::libm_walk` — is shared with the sibling probes (decision 0074), and the general
/// argument for each lives there. What could NOT move is the per-crate evidence below.
///
/// # What the shared needle list cannot see, MEASURED against this crate's `src/`
///
/// `banned_needles` misses three spellings: the angle-bracket one (`<f64>::exp(x)`), a call reached
/// through a generic bound (`T: Float`, `num_traits::Float::exp`), and a call split across two
/// lines by a `max_width` wrap. **None of the three occurs under `crates/vike-sim/src` today**
/// (measured 2026-09-27, when this file was split off). A list of spellings is an enumeration and
/// an enumeration is never a proof, so that sentence is a measurement rather than a reassurance.
///
/// # Why locating an item's end by INDENTATION is exact over this crate
///
/// `cfg_test_ranges` finds an item's end by indentation rather than by counting braces, which is
/// safe only where the tree really is rustfmt output. Measured over `crates/vike-sim/src`
/// 2026-09-27: seven of the eight test markers sit at column 0 and open the file's LAST item; the
/// eighth is `crates/vike-sim/src/latency.rs`'s test-only `LatencyGate::new`, an indented
/// `#[cfg(test)]` on one method, whose end the walk finds by that method's own indentation.
#[test]
fn production_code_calls_libm_not_the_platform() {
    let banned = banned_needles();
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let src = root.join("src");
    let mut found = Vec::new();
    let mut scanned: Vec<String> = Vec::new();
    // A `#[cfg(test)]` item whose end could not be located swallows the rest of its file exactly
    // the way a `break` would. That is the one QUIET failure of the range walk, so it is collected
    // and asserted rather than absorbed.
    let mut unclosed: Vec<String> = Vec::new();
    let mut stack = vec![src];
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir).expect("crate has a src/ directory") {
            let path = entry.expect("readable dir entry").path();
            if path.is_dir() {
                stack.push(path);
                continue;
            }
            if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                continue;
            }
            // `\` -> `/` so a path reads the same on the Windows box.
            let rel = path.strip_prefix(root).unwrap_or(&path).to_string_lossy().replace('\\', "/");
            let name = path.file_name().unwrap().to_string_lossy().to_string();
            let text = std::fs::read_to_string(&path).expect("readable source file");
            scanned.push(name);
            let lines: Vec<&str> = text.lines().collect();
            let test_items = cfg_test_ranges(&lines);
            for &(start, _, closed) in &test_items {
                if !closed {
                    unclosed.push(format!("  {rel}:{}", start + 1));
                }
            }
            for (i, line) in lines.iter().enumerate() {
                if test_items.iter().any(|&(start, end, _)| i >= start && i < end) {
                    continue; // inside a `#[cfg(test)]` item — not shipped
                }
                let code = line.trim_start();
                if code.starts_with("//") {
                    continue; // a doc comment naming `exp` is prose, not a call
                }
                for pat in &banned {
                    if line.contains(pat.as_str()) {
                        found.push(format!("  {rel}:{} {code}", i + 1));
                    }
                }
            }
        }
    }
    // Non-vacuity, aimed at the failure this scan is most likely to have: `src/` NESTS here
    // (`engine/`), so a walk that stopped at the top level would still open files and report a
    // confident zero while never reading the fill engine.
    for must in ["impact.rs", "queue_model.rs", "sim_broker.rs"] {
        assert!(
            scanned.iter().any(|s| s == must),
            "the scan never opened {must}, so an empty result proves nothing about the files this \
             gate exists for. Scanned {} files.",
            scanned.len()
        );
    }
    assert!(
        unclosed.is_empty(),
        "a `#[cfg(test)]` item's closing line could not be located, so everything below it went \
         UNSCANNED — the exact hole a `break` leaves, wearing a different cause. See \
         `vike_model::libm_walk::cfg_test_ranges`: the end is the item's own indentation followed \
         by a lone `}}`, or a `;` for a `mod NAME;` declaration.\n{}",
        unclosed.join("\n")
    );
    assert!(
        found.is_empty(),
        "production code must call the `libm` CRATE rather than `f64`'s platform-libm methods, so a \
         FILL PRICE does not depend on which box ran the replay — `crates/vike-sim/Cargo.toml`'s \
         `libm` line names the two sites and this file's module doc what each one's last bit \
         decides. BOTH spellings are banned, `x.exp()` and `f64::exp(x)`: same inherent method, \
         same libcall (see `vike_model::libm_walk::banned_needles`). `powi` is banned too — on MSVC \
         a `dev` build makes it a `pow()` libcall — and its cure is a MULTIPLICATION rather than \
         `libm`:\n{}",
        found.join("\n")
    );
}
