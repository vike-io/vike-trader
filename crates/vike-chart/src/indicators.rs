//! GUI indicator adapter — the per-window paint/colour state (`Active`) layered
//! over the shared `vike-indicators` compute core.
//!
//! The registry, the two orthogonal axes (picker [`Category`] vs render placement
//! [`RenderKind`]/[`OutputStyle`]) and the streaming [`Indicator`] trait ALL come
//! from `vike-indicators` (one source of truth, parity-gated against the Python
//! oracle `core/indicators/base.py`) and are re-exported here so the chart UI keeps
//! its `crate::indicators::…` paths. Only the egui colours + visibility and the
//! GUI-`Bar`→`vike_model::Bar` conversion live in this crate — that's paint state,
//! which has no place in the Qt-free compute core.
//!
//! ## Streaming overlays (why `Active` owns a live [`Indicator`])
//! `vike-indicators` proves `on_bar`-folded == `vectorize`, bit-for-bit. So rather
//! than a full-series `vectorize` every frame, each `Active` keeps a **persistent
//! streaming instance** folded over the **closed prefix only** (closed bars are
//! immutable and append-only), and [`Active::update`] does the cheapest correct
//! thing each frame:
//! - **no-op** when the closed series is unchanged (the common repaint frame),
//! - **[`Active::push_bar`]** — a single `on_bar` — when exactly one bar closed
//!   on top of an unchanged prefix (O(1)/O(window)),
//! - **[`Active::recompute_full`]** — reset + refold — only on a genuine
//!   structural change (first build, data reload, symbol/interval swap).
//!
//! The live *forming* bar — which mutates in place up to ~60×/s and which a
//! streaming fold cannot un-see — never touches the persistent instance: it is
//! previewed each call on a throwaway [`clone_box`], instead of the full-history
//! refold this path used to trigger.
//!
//! ⚠ **That clone is NOT "the tiny streaming state (O(window) bytes)", and a live
//! tick is NOT "microseconds regardless of history depth".** This paragraph said
//! both, and both are false for the ~150 indicators generated by
//! `vike_indicators`' `hist_indicator!`: those stream by history-RECOMPUTE and
//! carry a retained `hist: Vec<Bar>`, so `clone_box` deep-copies it EVERY FRAME.
//! Measured at `vwma`'s registry maximum `period = 400` under the old retention:
//! **4.6 MB and 1006 µs per frame** — 276 MB/s at 60 fps, most of a frame budget,
//! for ONE overlay, before any arithmetic runs.
//!
//! It is now bounded rather than merely smaller: `vike_indicators::keep_for` gives
//! a finite-window kernel `lookback_full + slack` instead of a multiple of it, which
//! is what took that same clone to ~7.8 µs. The claim above was written when every
//! streaming indicator really did carry O(window) state, and it survived the change
//! that made it untrue — the reason this correction names the measurement rather
//! than just softening the wording.
//!
//! ⚠ A USER-written indicator is worse still: its `Indicator` is the Rhai
//! interpreter, so `clone_box().on_bar(..)` is a full `RhaiIndicator` clone plus one
//! script evaluation per frame, and `recompute_full` is O(bars) interpreter calls on
//! the paint thread.
//!
//! Because the fold sequence (closed…, then forming) is exactly `vectorize`'s,
//! the on-screen values, lines, styles, colours and labels are bit-identical to
//! what a full recompute would have drawn — this is purely an efficiency design.
//!
//! [`clone_box`]: vike_indicators::BoxedClone::clone_box

