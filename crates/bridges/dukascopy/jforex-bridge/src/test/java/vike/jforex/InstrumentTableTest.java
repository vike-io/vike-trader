package vike.jforex;

import com.dukascopy.api.Instrument;
import com.dukascopy.api.instrument.IFinancialInstrument;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.Comparator;
import java.util.StringJoiner;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * THE DRIFT GATE of {@code crates/bridges/dukascopy/data/jforex_instruments.tsv}: that table is the
 * SDK's predefined {@link Instrument} constants rendered as text, and this test re-derives it from
 * the SDK jar on the classpath and fails on a difference. It is the only generator: the file is not
 * hand-edited. After a bump of the JForex-API pin in {@code build.gradle.kts}, regenerate with
 * {@code VIKE_REGEN_JFOREX_TABLE=1 ./gradlew --no-daemon test --tests vike.jforex.InstrumentTableTest}
 * and read the diff.
 *
 * No login, no network at run time: {@code Instrument} is a plain SDK class whose predefined
 * constants are initialised by its static block (the jar itself is resolved by gradle, the same
 * resolution the sidecar build already does).
 *
 * What the columns ARE (read from the SDK sources, {@code Instrument.java}): {@code pip_value},
 * {@code pip_scale} and {@code tick_scale} are constructor constants of the predefined instrument
 * (tick scale = pip scale + 1). The four {@code default_*} columns are the SDK's own DEFAULTS, and the
 * source comments say each "may be overridden in runtime after instrument subscription": they are
 * not venue facts. A CFD built by {@code createCfdInstrument} has the placeholder pip 0.01 / scale 2
 * and is marked {@code cfd-placeholder}.
 */
class InstrumentTableTest {

    static final String API_VERSION = System.getProperty("vike.jforexApiVersion", "?");

    static String num(double d) {
        return new BigDecimal(Double.toString(d)).stripTrailingZeros().toPlainString();
    }

    static String render() {
        StringBuilder out = new StringBuilder();
        out.append("# GENERATED by vike.jforex.InstrumentTableTest from the predefined constants of com.dukascopy.api.Instrument\n");
        out.append("# source: com.dukascopy.api:JForex-API:").append(API_VERSION)
           .append(" (Instrument.values(), no login, no network at generation)\n");
        out.append("# never hand-edit; regenerate: VIKE_REGEN_JFOREX_TABLE=1 gradlew test --tests vike.jforex.InstrumentTableTest\n");
        out.append("# default_* columns are the SDK's declared defaults that it overrides at run time after subscription, NOT venue facts\n");
        out.append("symbol\tpair\ttype\tpip_value\tpip_scale\ttick_scale\tdefault_min_amount\tdefault_amount_increment\t")
           .append("default_max_amount\tdefault_amount_per_contract\tgrid_basis\n");
        Instrument[] all = Instrument.values();
        Arrays.sort(all, Comparator.comparing(Instrument::name));
        for (Instrument i : all) {
            boolean placeholder = i.getType() == IFinancialInstrument.Type.CFD
                    && i.getPipScale() == 2 && i.getPipValue() == 0.01;
            StringJoiner row = new StringJoiner("\t");
            row.add(i.name()).add(i.toString()).add(i.getType().name())
               .add(num(i.getPipValue())).add(Integer.toString(i.getPipScale()))
               .add(Integer.toString(i.getTickScale()))
               .add(num(i.getMinTradeAmount())).add(num(i.getTradeAmountIncrement()))
               .add(num(i.getMaxTradeAmount())).add(num(i.getAmountPerContract()))
               .add(placeholder ? "cfd-placeholder" : "sdk-constant");
            out.append(row).append('\n');
        }
        return out.toString();
    }

    @Test
    void theCommittedTableIsWhatTheSdkSays() throws IOException {
        String want = render();
        Path file = Path.of(System.getProperty("vike.instrumentTable"));
        if ("1".equals(System.getenv("VIKE_REGEN_JFOREX_TABLE"))) {
            Files.writeString(file, want, StandardCharsets.UTF_8);
        }
        String have = Files.readString(file, StandardCharsets.UTF_8).replace("\r\n", "\n");
        assertEquals(want, have, "crates/bridges/dukascopy/data/jforex_instruments.tsv drifted from the SDK; "
                + "regenerate it (see this class's doc) and review the diff");
    }

    @Test
    void theRenderingHasAFloor() {
        // two empty renderings compare equal: the table must hold the FX rows the bridge trades
        assertTrue(Instrument.values().length > 100, "the SDK enum is unexpectedly small");
        assertTrue(render().contains("\nEURUSD\tEUR/USD\tFOREX\t0.0001\t4\t5\t1000\t1\t"));
    }
}
