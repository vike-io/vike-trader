//! What a book listing returned, as the markdown its chapter includes under the code: the metrics as a
//! table, each `.tsv` artifact as a table (its first [`TABLE_ROWS`] rows), each `chart_<name>.tsv` as an
//! inline SVG chart, any other artifact by name and size, and a refusal in its own words. Every byte
//! is a function of the outcome alone, so the committed page can be compared byte for byte.

use vike_user_research::{StudyError, StudyOutcome};

/// The most rows of a `.tsv` artifact a page shows.
const TABLE_ROWS: usize = 20;

/// The header a `chart_<name>.tsv` on a TIME axis starts with: `time` is epoch milliseconds, drawn as days.
const CHART_HEADER: &str = "time\tvalue\tseries\tkind";

/// The header a `chart_<name>.tsv` on a NUMERIC axis starts with (a reliability diagram, a curve): `x` is
/// any finite number, drawn as one.
const NUMERIC_CHART_HEADER: &str = "x\tvalue\tseries\tkind";

/// The drawing's size in SVG units, and its margins around the plot.
const WIDTH: f64 = 720.0;
const HEIGHT: f64 = 280.0;
const LEFT: f64 = 76.0;
const RIGHT: f64 = 12.0;
const TOP: f64 = 12.0;
const BOTTOM: f64 = 52.0;

/// One color per series, in order; a seventh series takes the first again.
const PALETTE: [&str; 6] = ["#4e79a7", "#f28e2b", "#e15759", "#59a14f", "#b07aa1", "#76b7b2"];

/// The page for listing `name`: what it returned, or its refusal, ending in exactly one newline. `Err`
/// names what cannot be drawn.
pub(crate) fn render(
    name: &str,
    outcome: &Result<StudyOutcome, StudyError>,
) -> Result<String, String> {
    let mut out = format!(
        "<!-- Generated by the book gate (crates/vike-strategy-sandbox/tests/book_listings.rs) from \
         listings/{name}/: never edit it by hand. -->\n\n"
    );
    let outcome = match outcome {
        Ok(outcome) => outcome,
        Err(refusal) => {
            out.push_str(&format!("The study refused:\n\n```text\n{refusal}\n```\n"));
            return Ok(out);
        }
    };
    if !outcome.metrics().is_empty() {
        out.push_str("| metric | value |\n| :-- | --: |\n");
        for (metric, value) in outcome.metrics() {
            out.push_str(&format!("| {} | {} |\n", cell(metric), number(*value)));
        }
        out.push('\n');
    }
    for (file, body) in outcome.artifacts() {
        if file.starts_with("chart_") && file.ends_with(".tsv") {
            out.push_str(&chart(file, body)?);
        } else if file.ends_with(".tsv") {
            out.push_str(&table(file, body));
        } else {
            out.push_str(&format!("`{file}`: {} bytes, not shown.\n", body.len()));
        }
        out.push('\n');
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    Ok(out)
}

/// A number as a page shows it: six significant digits, every digit of an integer part, no trailing
/// zero, scientific notation only far from one.
pub(crate) fn number(value: f64) -> String {
    if value.is_nan() {
        return "NaN".to_string();
    }
    if value.is_infinite() {
        return if value > 0.0 { "inf" } else { "-inf" }.to_string();
    }
    if value == 0.0 {
        return "0".to_string();
    }
    let scientific = format!("{value:.5e}");
    let (mantissa, exponent) = scientific.split_once('e').expect("`{:e}` writes an exponent");
    let exponent: i32 = exponent.parse().expect("`{:e}` writes an integer exponent");
    if (-4..15).contains(&exponent) {
        let decimals = (5 - exponent).max(0) as usize;
        trim_zeros(format!("{value:.decimals$}"))
    } else {
        format!("{}e{exponent}", trim_zeros(mantissa.to_string()))
    }
}

fn trim_zeros(text: String) -> String {
    if text.contains('.') {
        text.trim_end_matches('0').trim_end_matches('.').to_string()
    } else {
        text
    }
}

/// A markdown table cell: a `|` would end the cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

/// Text inside SVG.
fn xml(text: &str) -> String {
    text.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;")
}

/// A `.tsv` artifact as a markdown table: its header and its first [`TABLE_ROWS`] rows.
fn table(file: &str, body: &str) -> String {
    let mut lines = body.lines();
    let Some(header) = lines.next() else {
        return format!("`{file}`: empty.\n");
    };
    let rows: Vec<&str> = lines.collect();
    let columns = header.split('\t').count();
    let row = |line: &str| {
        format!("| {} |\n", line.split('\t').map(cell).collect::<Vec<_>>().join(" | "))
    };
    let shown = rows.len().min(TABLE_ROWS);
    let mut out = format!("`{file}`, {shown} of {} row(s):\n\n", rows.len());
    out.push_str(&row(header));
    out.push_str(&format!("|{}\n", " --: |".repeat(columns)));
    for line in &rows[..shown] {
        out.push_str(&row(line));
    }
    out
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Kind {
    Line,
    Bars,
    Points,
}

/// One series of a chart: its name, its kind and its points `(x, value)`, in file order (`x` is the
/// epoch milliseconds of a time axis).
struct Series {
    name: String,
    kind: Kind,
    points: Vec<(f64, f64)>,
}

/// A `chart_<name>.tsv` artifact as an inline SVG chart in a `<figure>`. No blank line inside, so
/// markdown passes the whole block through as HTML.
fn chart(file: &str, body: &str) -> Result<String, String> {
    let title = file.trim_start_matches("chart_").trim_end_matches(".tsv").replace('_', " ");
    let mut lines = body.lines();
    let numeric = match lines.next() {
        Some(CHART_HEADER) => false,
        Some(NUMERIC_CHART_HEADER) => true,
        _ => {
            return Err(format!(
                "{file}: a chart's first line is {CHART_HEADER:?} (a time axis) or \
                 {NUMERIC_CHART_HEADER:?} (a numeric axis)"
            ));
        }
    };
    let axis = if numeric { "x" } else { "time" };
    let mut series: Vec<Series> = Vec::new();
    for (at, line) in lines.enumerate() {
        let row = at + 2;
        let columns: Vec<&str> = line.split('\t').collect();
        let [position, value, name, kind] = columns[..] else {
            return Err(format!("{file} line {row}: four columns, {axis}, value, series and kind"));
        };
        let position =
            if numeric {
                position.parse::<f64>().ok().filter(|x| x.is_finite()).ok_or_else(|| {
                    format!("{file} line {row}: x {position:?} is no finite number")
                })?
            } else {
                let time: i64 = position
                    .parse()
                    .map_err(|_| format!("{file} line {row}: time {position:?} is no integer"))?;
                time as f64
            };
        let value: f64 = value
            .parse()
            .map_err(|_| format!("{file} line {row}: value {value:?} is no number"))?;
        let kind = match kind {
            "line" => Kind::Line,
            "bars" => Kind::Bars,
            "points" => Kind::Points,
            other => {
                return Err(format!(
                    "{file} line {row}: kind {other:?} is not line, bars or points"
                ));
            }
        };
        let at = match series.iter().position(|s| s.name == name) {
            Some(at) => at,
            None => {
                series.push(Series { name: name.to_string(), kind, points: Vec::new() });
                series.len() - 1
            }
        };
        if series[at].kind != kind {
            return Err(format!("{file} line {row}: series {name:?} changes its kind"));
        }
        series[at].points.push((position, value));
    }
    let finite = || series.iter().flat_map(|s| &s.points).filter(|(_, v)| v.is_finite());
    let Some((first, _)) = finite().next() else {
        return Err(format!("{file}: no finite point to draw"));
    };
    let (mut x0, mut x1, mut y0, mut y1) = (*first, *first, f64::INFINITY, f64::NEG_INFINITY);
    for (time, value) in finite() {
        (x0, x1, y0, y1) = (x0.min(*time), x1.max(*time), y0.min(*value), y1.max(*value));
    }
    if series.iter().any(|s| s.kind == Kind::Bars) {
        (y0, y1) = (y0.min(0.0), y1.max(0.0));
    }
    let (data_low, data_high) = (y0, y1);
    if x0 == x1 {
        (x0, x1) = (x0 - 1.0, x1 + 1.0);
    }
    let pad = if y0 == y1 { y0.abs().max(1.0) } else { (y1 - y0) * 0.05 };
    (y0, y1) = (y0 - pad, y1 + pad);

    let (plot_w, plot_h) = (WIDTH - LEFT - RIGHT, HEIGHT - TOP - BOTTOM);
    let x = |time: f64| LEFT + (time - x0) / (x1 - x0) * plot_w;
    let y = |value: f64| TOP + (y1 - value) / (y1 - y0) * plot_h;
    let mut svg = format!(
        "<figure class=\"chart\">\n<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 {WIDTH} {HEIGHT}\" \
         width=\"{WIDTH}\" height=\"{HEIGHT}\" role=\"img\" aria-label=\"{t}\" style=\"max-width:100%;height:auto\" \
         font-family=\"sans-serif\" font-size=\"12\" fill=\"currentColor\">\n<title>{t}</title>\n\
         <rect x=\"{LEFT}\" y=\"{TOP}\" width=\"{plot_w}\" height=\"{plot_h}\" fill=\"none\" \
         stroke=\"currentColor\" stroke-opacity=\"0.4\"/>\n",
        t = xml(&title)
    );
    // The value axis: the lowest and the highest value drawn, and zero between them under bars.
    let mut marks = vec![data_low, data_high];
    if data_low < 0.0 && data_high > 0.0 && series.iter().any(|s| s.kind == Kind::Bars) {
        marks.push(0.0);
    }
    for mark in marks {
        let at = y(mark);
        svg.push_str(&format!(
            "<line x1=\"{LEFT}\" y1=\"{at:.1}\" x2=\"{:.1}\" y2=\"{at:.1}\" stroke=\"currentColor\" \
             stroke-opacity=\"0.2\"/>\n<text x=\"{:.1}\" y=\"{:.1}\" text-anchor=\"end\">{}</text>\n",
            WIDTH - RIGHT,
            LEFT - 6.0,
            at + 4.0,
            number(mark)
        ));
    }
    // The x axis: its first and last position, a day on a time axis and a number on a numeric one.
    let below = TOP + plot_h + 16.0;
    for (at, anchor) in [(x0, "start"), (x1, "end")] {
        let label =
            if numeric { number(at) } else { vike_model::time::epoch_ms_to_utc_date(at as i64) };
        svg.push_str(&format!(
            "<text x=\"{:.1}\" y=\"{below:.1}\" text-anchor=\"{anchor}\">{label}</text>\n",
            x(at)
        ));
    }
    let mut legend_x = LEFT;
    for (index, s) in series.iter().enumerate() {
        let color = PALETTE[index % PALETTE.len()];
        match s.kind {
            Kind::Line => {
                // A non-finite value breaks the line rather than joining across the gap.
                for run in s.points.split(|(_, v)| !v.is_finite()).filter(|run| !run.is_empty()) {
                    let points: Vec<String> =
                        run.iter().map(|(t, v)| format!("{:.1},{:.1}", x(*t), y(*v))).collect();
                    svg.push_str(&format!(
                        "<polyline fill=\"none\" stroke=\"{color}\" stroke-width=\"1.5\" points=\"{}\"/>\n",
                        points.join(" ")
                    ));
                }
            }
            Kind::Points => {
                for (t, v) in s.points.iter().filter(|(_, v)| v.is_finite()) {
                    svg.push_str(&format!(
                        "<circle cx=\"{:.1}\" cy=\"{:.1}\" r=\"2\" fill=\"{color}\"/>\n",
                        x(*t),
                        y(*v)
                    ));
                }
            }
            Kind::Bars => {
                let width = (plot_w / s.points.len() as f64 * 0.8).max(0.5);
                let base = y(0.0);
                for (t, v) in s.points.iter().filter(|(_, v)| v.is_finite()) {
                    let top = y(*v).min(base);
                    svg.push_str(&format!(
                        "<rect x=\"{:.1}\" y=\"{top:.1}\" width=\"{width:.1}\" height=\"{:.1}\" fill=\"{color}\"/>\n",
                        x(*t) - width / 2.0,
                        (y(*v) - base).abs()
                    ));
                }
            }
        }
        let legend_y = HEIGHT - 10.0;
        svg.push_str(&format!(
            "<rect x=\"{legend_x:.1}\" y=\"{:.1}\" width=\"10\" height=\"10\" fill=\"{color}\"/>\n\
             <text x=\"{:.1}\" y=\"{legend_y:.1}\">{}</text>\n",
            legend_y - 9.0,
            legend_x + 14.0,
            xml(&s.name)
        ));
        legend_x += 14.0 + 7.0 * s.name.chars().count() as f64 + 18.0;
    }
    svg.push_str(&format!("</svg>\n<figcaption>{}</figcaption>\n</figure>\n", xml(&title)));
    Ok(svg)
}

/// The committed drawings `self_check` compares byte for byte: each `book_listings/charts/<name>.tsv`
/// drawn by [`chart`] must equal the `<name>.html` beside it. `chart_time` is a time-axis chart pinned
/// as the renderer drew it BEFORE the numeric axis existed, so that axis cannot move a time chart;
/// `chart_reliability` is a reliability diagram on the numeric axis. A difference prints the derived
/// drawing between `=== derived <file> ===` and `=== end ===`.
const COMMITTED_DRAWINGS: [(&str, &str, &str); 2] = [
    (
        "chart_time.tsv",
        include_str!("charts/chart_time.tsv"),
        include_str!("charts/chart_time.html"),
    ),
    (
        "chart_reliability.tsv",
        include_str!("charts/chart_reliability.tsv"),
        include_str!("charts/chart_reliability.html"),
    ),
];

/// The renderer's own check, run before any listing: the number format, every kind drawn, the
/// refusals of a malformed chart, and the committed drawings.
pub(crate) fn self_check() {
    let mut differ = Vec::new();
    for (file, body, committed) in COMMITTED_DRAWINGS {
        let derived = chart(file, body).unwrap_or_else(|why| format!("refused: {why}\n"));
        if derived != committed {
            println!("=== derived {file} ===\n{derived}=== end ===");
            differ.push(file);
        }
    }
    assert!(
        differ.is_empty(),
        "{differ:?} drew otherwise than committed: LOOK at the derived drawing"
    );
    for (value, shown) in [
        (4344.0, "4344"),
        (0.123_456_789, "0.123457"),
        (-0.0, "0"),
        (9.999_999_6, "10"),
        (1_234_567.891, "1234568"),
        (-1.5e-7, "-1.5e-7"),
        (f64::NAN, "NaN"),
        (f64::NEG_INFINITY, "-inf"),
    ] {
        assert_eq!(number(value), shown, "number({value})");
    }
    let body = "time\tvalue\tseries\tkind\n0\t1\ta\tline\n86400000\tNaN\ta\tline\n172800000\t3\ta\tline\n\
                259200000\t4\ta\tline\n0\t-1\tb|<\tbars\n86400000\t2\tc\tpoints\n";
    let drawn = chart("chart_check.tsv", body).expect("a well-formed chart draws");
    assert_eq!(drawn.matches("<polyline").count(), 2, "a NaN breaks the line in two:\n{drawn}");
    assert!(drawn.contains("<circle") && drawn.contains(">b|&lt;</text>"), "{drawn}");
    assert!(drawn.contains("1970-01-01") && drawn.contains("1970-01-04"), "{drawn}");
    assert!(!drawn.contains("\n\n"), "a blank line would end the HTML block:\n{drawn}");
    for bad in [
        "time\tvalue\tseries\n0\t1\ta\n",
        "time\tvalue\tseries\tkind\n0\t1\ta\tarea\n",
        "time\tvalue\tseries\tkind\n0\t1\ta\tline\n1\t2\ta\tbars\n",
        "time\tvalue\tseries\tkind\n0.5\t1\ta\tline\n",
        "time\tvalue\tseries\tkind\n0\tNaN\ta\tline\n",
        "x\tvalue\tseries\tkind\nNaN\t1\ta\tline\n",
        "x\tvalue\tseries\tkind\ninf\t1\ta\tpoints\n",
        "position\tvalue\tseries\tkind\n0\t1\ta\tline\n",
    ] {
        assert!(chart("chart_bad.tsv", bad).is_err(), "a malformed chart must be refused:\n{bad}");
    }
    let refused =
        render("x", &Err(StudyError::Study("no bars".into()))).expect("a refusal is shown");
    assert!(refused.contains("```text\n") && refused.contains("no bars"), "{refused}");
}
