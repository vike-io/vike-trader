/// The covered function, folded over its own corpus.
///
/// Returns rows in a FIXED order; [`PLATFORM_INVARIANT`] is compared positionally, so a reordering
/// is a re-record rather than a silent re-pairing.
///
/// ⚠ This returned TWO rows, then ONE when `metrics.rs` was deleted, and TWO again now that the
/// TPE sampler moved into this crate and brought its probe. The count is not the point and never
/// was: each corpus is built and folded INDEPENDENTLY, so adding or removing one cannot move
/// another's hash - which is what let the arriving row keep the value recorded for it in
/// vike-backtest, and what let the departing one leave without a re-record.
fn production_rows() -> Vec<Row> {
    let mut out = Vec::new();

    // --- infer::GbdtModel::predict_proba — `libm::exp(-sigmoid * raw_score)`.
    //
    // ⚠ The SIGMOID is swept, not just the feature row, and that is a non-vacuity requirement
    // rather than thoroughness. The committed fixture's trees have one leaf and three leaves, so
    // `raw_score` takes at most THREE distinct values no matter how many rows are fed in — a corpus
    // over rows alone would report `distinct = 3` and hash identically on any two platforms that
    // happened to agree on three numbers. `sigmoid` is a genuine header-parsed parameter (LightGBM
    // writes `objective=binary sigmoid:N` and it is "not always 1.0", per `parse.rs`'s own doc), so
    // sweeping it is exercising the real configuration space, not manufacturing variety.
    //
    // Parsing a model per sigmoid is the honest way to do it: `Objective::Binary { sigmoid }` is
    // built by the parser and there is no public setter, and re-parsing also keeps the row covering
    // the header path that produces the value.
    {
        let mut s = 0x0fed_cba9_8765_4321u64;
        let mut vals = Vec::with_capacity(SAMPLES);
        // Three features (`max_feature_idx=2`), with `feature_infos` of `[0:1] [0:9] [0:2]` — the
        // rows below span each range and overshoot it, because a split threshold is a `<=` and a
        // row outside the training range is an ordinary inference input rather than an error.
        let rows: [[f64; 3]; 8] = [
            [0.0, 0.0, 0.0],
            [1.0, 9.0, 2.0],
            [0.0, 3.0, 2.0],
            [1.0, 4.5, 0.0],
            [0.5, 4.4999, 1.0],
            [0.5, 4.5001, 1.0],
            [-3.0, -1.0, -1.0],
            [7.0, 40.0, 11.0],
        ];
        while vals.len() < SAMPLES {
            // Strictly positive: the parser refuses `sigmoid <= 0`, so a non-positive draw would be
            // an `unwrap` panic rather than a sample.
            let sigmoid = 0.01 + lcg(&mut s) * 8.0;
            let text = FIXTURE.replace("sigmoid:1", &format!("sigmoid:{sigmoid}"));
            let model = parse_model_text(&text).expect("the committed fixture parses");
            for row in &rows {
                vals.push(model.predict_proba(row));
            }
        }
        vals.truncate(SAMPLES);
        out.push(finish("infer::GbdtModel::predict_proba (exp)", &vals));
    }

    // --- tpe::TpeOptimizer - the ask/tell proposal stream.
    //
    // ⚠ This row came from `crates/vike-backtest/tests/libm_platform_probe.rs` with the sampler
    // it measures, and it arrives UNGATED where it used to sit behind `hist-replay` - so the
    // default roster lane runs it now instead of only the `datafusion-store` lane. The corpus,
    // the constants and the recorded hash are unchanged; both crates' hashing machinery is a
    // byte-identical per-crate copy, so the pin transferred rather than needing a re-record.
    out.extend(tpe_rows());

    out
}

/// Drive the TPE ask/tell loop and hash every proposed coordinate.
///
/// ⚠ The loop is driven rather than `gaussian`/`gaussian_pdf` called directly, and not only because
/// both are private. Driving the loop is the STRONGER pin: the failure that matters is not "the pdf
/// is one ulp out", it is "a different one of the `n_candidates` draws won the Expected-Improvement
/// argmax, and every proposal after it differs". A row over the pdf alone would report a last bit;
/// this row reports the re-routed search.
///
/// `n_startup` is deliberately small and the trial count large: `ask` samples UNIFORMLY — no
/// transcendental at all — until `trials.len() >= n_startup.max(2)`, so a corpus dominated by
/// startup draws would pin the LCG and call it a pin of the Parzen sampler. The assertion at the
/// bottom measures that ratio rather than trusting this paragraph.
fn tpe_rows() -> Vec<Row> {
    use vike_ml::tpe::{ParamDomain, TpeOptimizer};

    const TRIALS: usize = 64;
    const SEEDS: u64 = 48;
    const STARTUP: usize = 4;
    const DIMS: usize = 3;

    let mut vals = Vec::with_capacity(SEEDS as usize * TRIALS * DIMS);
    let mut startup_draws = 0usize;
    for seed in 0..SEEDS {
        let space = vec![
            ("x".to_string(), ParamDomain::continuous(-4.0, 6.5)),
            ("y".to_string(), ParamDomain::continuous(0.001, 25.0)),
            // An INTEGRAL axis beside the two continuous ones: it is rounded on the way out, so it
            // exercises the quantised path a real `[sweep]` table produces — where a last-bit move
            // in a proposal becomes a WHOLE-STEP move in the config that gets run.
            ("k".to_string(), ParamDomain::continuous_integral(1.0, 40.0)),
        ];
        let mut opt =
            TpeOptimizer::new(space, seed, 0.25).with_n_startup(STARTUP).with_n_candidates(24);
        for t in 0..TRIALS {
            let params = opt.ask();
            // ⚠ A PURE-ARITHMETIC objective. A `.sin()` bowl here would make the SCORES
            // platform-dependent, the good/bad split differ, and this row diverge because of the
            // objective rather than because of the sampler — the false positive the module doc
            // warns about, planted in the one place it would be hardest to see.
            let mut score = 0.0f64;
            for (i, v) in params.values().enumerate() {
                let centre = 0.5 + i as f64;
                score -= (v - centre) * (v - centre);
                vals.push(*v);
            }
            opt.tell(&params, score);
            if t < STARTUP {
                startup_draws += DIMS;
            }
        }
    }
    // Non-vacuity SPECIFIC to this row, beyond the shared `distinct` floor: prove the corpus is
    // mostly TPE proposals rather than uniform startup draws. Without it the row could pin the LCG
    // — portable by construction — and report a confident pass about a sampler it never reached.
    assert!(
        startup_draws * 4 < vals.len(),
        "startup (uniform, transcendental-free) draws are {startup_draws} of {} samples — this row \
         would be pinning the LCG rather than the Parzen sampler. Raise TRIALS or lower STARTUP.",
        vals.len()
    );
    vec![finish("tpe::TpeOptimizer (gaussian log+cos, gaussian_pdf exp)", &vals)]
}

/// ⚠ **ONE set of constants for EVERY platform — that is the entire claim.**
///
/// ⚠ **Every hash below is the literal `"RECORD"`, a PLACEHOLDER that fails by construction, and
/// that is deliberate.** The convention is the analytics twin's
/// (`crates/vike-analytics/tests/libm_platform_probe.rs`'s `PLATFORM_INVARIANT`): rows are
/// sometimes written on a box that cannot run cargo, and a plausible-looking hex literal invented
/// there is INDISTINGUISHABLE from a recorded one while pinning nothing. `"RECORD"` cannot match
/// any FNV output, so [`converted_functions_are_platform_invariant`] stays red until a human RUNS
/// this file on Linux/glibc AND on Windows/MSVC, confirms the two runs agree bit-for-bit, and
/// pastes the agreed hash in. **A red row spelled `"RECORD"` is an UNFINISHED RECORDING, not a
/// regression.**
///
/// ⚠ **Re-record by RUNNING, never by editing a digit**, and never from ONE box.
///
/// ⚠ **A per-platform table (`#[cfg(windows)]` / `#[cfg(unix)]`) is NOT a repair and must never be
/// added.** It would make the gate green by asserting that a probability may depend on the box.
/// ⚠ It is a TWO-row table again, the second row being the TPE sampler's, which arrived WITH the
/// sampler from vike-backtest carrying the hash recorded there. Before that it was two for a
/// different reason and then one: the removed row was
/// `("metrics::binary_logloss (log x2)", "b4aa8b5ff07afed5")`, and it is written out here rather
/// than merely dropped so that a reader who finds the old hash in git history knows it was RETIRED
/// with its function and is not a value somebody failed to re-record. The surviving hash is
/// unchanged: `production_rows` builds each corpus independently, so removing one cannot move the
/// other.
const PLATFORM_INVARIANT: [(&str, &str); 2] = [
    ("infer::GbdtModel::predict_proba (exp)", "cd322ade65352484"),
    ("tpe::TpeOptimizer (gaussian log+cos, gaussian_pdf exp)", "d80ed29b912b84e0"),
];

/// The cross-platform proof, as a GATE rather than a diff somebody has to remember to run.
///
/// NOT `#[ignore]`d: CI runs it on Linux every PR and `just t vike-ml` runs it on the Windows dev
/// box, both against the same committed table.
#[test]
fn converted_functions_are_platform_invariant() {
    let got = production_rows();
    assert_eq!(
        got.len(),
        PLATFORM_INVARIANT.len(),
        "row count drifted from PLATFORM_INVARIANT — it must be re-recorded"
    );

    let mut bad = Vec::new();
    for (r, (want_label, want_hash)) in got.iter().zip(PLATFORM_INVARIANT.iter()) {
        assert_eq!(&r.label, want_label, "row ORDER drifted — the compare is positional");
        if r.hash != *want_hash {
            bad.push(format!("  {:<40} want={want_hash} got={}", r.label, r.hash));
        }
    }

    // Non-vacuity BEFORE the hashes: a thin row is a defect whether or not its hash matched, and an
    // author re-recording a `"RECORD"` row must be told about it before pasting.
    let thin: Vec<String> = got
        .iter()
        .filter(|r| r.distinct < MIN_DISTINCT)
        .map(|r| format!("  {:<40} {} distinct finite of {} samples", r.label, r.distinct, r.n))
        .collect();
    assert!(
        thin.is_empty(),
        "a pinned row's corpus is too thin to detect a last-bit divergence: it would hash \
         identically on every platform and read as a PASS. For `predict_proba` the usual cause is \
         a sigmoid sweep that stopped sweeping — the fixture's trees give only THREE distinct raw \
         scores on their own. WIDEN the corpus, never lower MIN_DISTINCT ({MIN_DISTINCT}):\n{}",
        thin.join("\n")
    );

    if !bad.is_empty() {
        let paste: String =
            got.iter().map(|r| format!("    (\"{}\", \"{}\"),\n", r.label, r.hash)).collect();
        panic!(
            "\nvike-ml output moved away from the platform pin:\n{}\n\n\
             There is no tolerance here to widen, and hand-editing a digit defeats the gate.\n\
             ⚠ Do NOT reach for this crate's other gates to decide whether the move matters:\n\
             `train_infer_equality.rs` and `real_model_golden.rs` both budget 1e-12 for one `exp`\n\
             through two libms, so a last-bit move passes them silently. That is why this file is\n\
             a BIT comparison.\n\
             If the want= column reads RECORD this is an UNFINISHED RECORDING rather than a\n\
             regression: run this file on BOTH Windows and Linux, confirm they agree, paste.\n\
             Otherwise establish WHY first:\n\
               (a) an intended numeric change — re-record on BOTH boxes and pin the agreed hash; or\n\
               (b) a call site went back to `(…).exp()` / `(…).ln()`, in which case the two\n\
                   platforms will NOT agree and the fix is in the source, not here.\n\n\
             const PLATFORM_INVARIANT: [(&str, &str); {}] = [\n{paste}];\n",
            bad.join("\n"),
            got.len(),
        );
    }
}

/// The control arm for the non-vacuity threshold itself.
///
/// ⚠ Without this, `MIN_DISTINCT` is an assertion nobody has checked DISCRIMINATES. A `distinct`
/// computation that counted samples rather than distinct values would pass both rows above while
/// the guard did nothing.
#[test]
fn the_non_vacuity_check_discriminates() {
    let constant: Vec<f64> = (0..SAMPLES).map(|_| 0.5f64).collect();
    assert!(
        finish("control::constant", &constant).distinct < MIN_DISTINCT,
        "the non-vacuity check does not discriminate: a constant series passed it"
    );
    let nans: Vec<f64> = (0..SAMPLES).map(|_| f64::NAN).collect();
    assert_eq!(
        finish("control::nan", &nans).distinct,
        0,
        "an all-NaN row must report ZERO distinct FINITE values — the shape a broken corpus takes \
         here, since a model that failed to parse would fold NaNs rather than refusing outright"
    );
    // The degenerate `predict_proba` corpus this file's sigmoid sweep exists to avoid, run as a
    // real control: one model, many rows. If THIS ever passes the floor, the fixture has grown more
    // trees and the sigmoid sweep's justification needs rewriting rather than deleting.
    let model = parse_model_text(FIXTURE).expect("the committed fixture parses");
    let mut s = 0x2222_3333_4444_5555u64;
    let vals: Vec<f64> = (0..SAMPLES)
        .map(|_| {
            let row = [lcg(&mut s) * 2.0, lcg(&mut s) * 12.0, lcg(&mut s) * 3.0];
            model.predict_proba(&row)
        })
        .collect();
    assert!(
        finish("control::one-model", &vals).distinct < MIN_DISTINCT,
        "one fixture model over many rows produced {} distinct probabilities — the committed \
         two-tree fixture should give at most three. If it has grown, update the `predict_proba` \
         row's comment; do not simply delete this control.",
        finish("control::one-model", &vals).distinct
    );
}

