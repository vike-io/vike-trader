//! The cross-platform PIN for this crate's TWO transcendental sites — the gate `vike-indicators`,
//! `vike-analytics` and `vike-mm` each carry, and which vike-ml's conversion landed WITHOUT.
//!
//! IEEE 754 requires `+ - * /` and `sqrt` to be correctly rounded and requires NOTHING of
//! `ln`/`exp`, so an `f64` METHOD call reaches whichever libm the PLATFORM ships — MSVC's CRT on
//! the Windows dev box, glibc on the CI box and every CI runner — and the two disagree in the last bit.
//! `crates/vike-ml/Cargo.toml`'s `libm` line names both sites as this crate's whole share of
//! `docs/decisions/0032-transcendentals-come-from-the-libm-crate-not-the-platform.md`, and both
//! already route through the `libm` CRATE. Nothing in the tree would have noticed the next edit
//! moving either one back.
//!
//! # What each row reaches, stated at its true size
//!
//! * `infer::GbdtModel::predict_proba` is **the probability a live binary decides on** — the whole
//!   point of this crate is that a trading binary predicts with no native dependency, so this is
//!   the number that leaves it. Everything UNDER the `exp` was already portable: `raw_score` is a
//!   plain `+` fold over leaf values and the walk selecting them is comparisons and integer bit
//!   tests. So the site's own doc is right that the conversion moves the probability by at most an
//!   ulp and cannot move a routing decision by itself — but "cannot move a routing decision" is a
//!   statement about a threshold nobody has pinned, and this row is what makes the value itself a
//!   property of the model rather than of the box.
//!
//! ⚠ **There was a SECOND row until `metrics.rs` was deleted, and its removal did not shrink what
//! this file covers.** It pinned `metrics::binary_logloss`'s two `libm::log` calls, on the argument
//! that the function was latent public-API surface whose first caller would be measuring `libm`
//! from its first run. That function had no caller in this workspace, its only import was the last
//! thing tying this crate to `vike-model`, and it went. This file's subject is "this crate's
//! transcendental sites"; there is now ONE, and the row above is still all of them. Do not re-add a
//! row for a function that no longer exists, and do not read the shorter table as reduced coverage.
//!
//! ⚠ The row is not redundant with this crate's existing gates, and the reason is a TOLERANCE.
//! `crates/vike-ml/tests/train_infer_equality.rs` and `crates/vike-ml/tests/real_model_golden.rs`
//! both budget `1e-12` for "one `exp` through two libms", stated in those words — so a last-bit
//! move is four orders inside their budget and passes them silently. Only a BIT comparison can see
//! it, which is what this file adds.
//!
//! # ⚠ The corpus is PURE ARITHMETIC, and that is load-bearing
//!
//! Every input is generated by an integer LCG plus `+ - * /`, never by `.sin()`/`.cos()`. Those are
//! themselves platform-dependent (MEASURED — `crates/vike-analytics/tests/libm_platform_probe.rs`'s
//! Part A sweeps them as its own control), so generating inputs with them would make both rows
//! diverge because of the INPUTS rather than because of the function under test.
//!
//! ```text
//! <cargo> test -p vike-ml --test libm_platform_probe
//! ```

use vike_ml::parse::parse_model_text;
use vike_model::libm_walk::{banned_needles, cfg_test_ranges};

/// The same committed two-tree binary model `crates/vike-ml/src/infer.rs`'s own unit tests parse.
///
/// ⚠ Its tree 1 has THREE leaves and its tree 0 has one, so `raw_score` takes at most THREE
/// distinct values however many feature rows are thrown at it. That single fact is what shapes the
/// `predict_proba` row below — see its comment.
const FIXTURE: &str = include_str!("fixtures/two_trees_binary_v4.txt");

// =================================================================================================
// The shared hashing/corpus machinery. Deliberately a per-crate COPY — see `Fnv`'s own doc for why
// every sibling probe carries the same one. ⚠ This pointed at `cfg_test_ranges`'s doc for that
// argument until decision 0074 moved the TEXT machinery out to `vike_model::libm_walk`; the parser
// is SHARED now and this is not, so the two no longer make one argument.
// =================================================================================================

/// FNV-1a over `f64::to_bits`, NaN canonicalised so a NaN's sign and payload — neither of which the
/// architecture pins — cannot report a divergence that is not one. The same hasher the sibling
/// probes use, so a row moved between crates hashes identically.
struct Fnv(u64);

impl Fnv {
    fn new() -> Self {
        Fnv(0xcbf2_9ce4_8422_2325)
    }
    fn push(&mut self, v: f64) {
        let bits = if v.is_nan() { 0x7ff8_0000_0000_0000u64 } else { v.to_bits() };
        for b in bits.to_le_bytes() {
            self.0 ^= u64::from(b);
            self.0 = self.0.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
    fn hex(&self) -> String {
        format!("{:016x}", self.0)
    }
}

/// Deterministic pseudo-random `f64` in `(0, 1)` from a pure-integer LCG. No transcendental
/// anywhere in here, for the reason the module doc gives.
fn lcg(seed: &mut u64) -> f64 {
    *seed = seed.wrapping_mul(6_364_136_223_846_793_005).wrapping_add(1_442_695_040_888_963_407);
    ((*seed >> 11) as f64) / ((1u64 << 53) as f64)
}

/// Samples per row.
const SAMPLES: usize = 4096;

/// One row's verdict over its own corpus.
struct Row {
    label: &'static str,
    hash: String,
    n: usize,
    /// ⚠ NON-VACUITY GUARD — how many DISTINCT FINITE values the samples took. A row that collapses
    /// to one value hashes identically on every platform and reads as a PASS while pinning nothing.
    /// The analytics twin caught a real instance of exactly that (`overfit::pbo_cscv`).
    distinct: usize,
}

fn finish(label: &'static str, vals: &[f64]) -> Row {
    let mut h = Fnv::new();
    for &v in vals {
        h.push(v);
    }
    let mut bits: Vec<u64> = vals.iter().filter(|v| v.is_finite()).map(|v| v.to_bits()).collect();
    bits.sort_unstable();
    bits.dedup();
    Row { label, hash: h.hex(), n: vals.len(), distinct: bits.len() }
}

/// Smallest number of DISTINCT finite values a row may carry before its pin is treated as vacuous.
const MIN_DISTINCT: usize = 64;

