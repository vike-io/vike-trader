/// Production code in this crate must reach a transcendental through the `libm` CRATE.
///
/// ⚠ Not redundant with the hash table. That table pins TWO functions; this crate also holds the
/// learner, the grid search, the importance and the fit cache, and a new transcendental in any of
/// them would be invisible to the corpus above.
///
/// Scope: every `.rs` under `src/`, recursively, MINUS each file's test-item ranges. There are NO
/// exemptions and there should not need to be: measured 2026-08-29, `crates/vike-ml/src` contains
/// three `vike_model::libm_walk::BANNED_FNS` calls and ALL THREE are inside `gbdt_learner.rs`'s
/// test module (its synthetic `sin`/`cos` feature fixture), so this gate starts at a clean zero
/// rather than at a grandfathered list.
///
/// # What was MEASURED on THIS crate, and why the shared walk is the right shape for it
///
/// The text machinery this gate runs on — `banned_needles` and `cfg_test_ranges` — moved to
/// `vike_model::libm_walk` under decision 0074, and the GENERAL argument for each choice (two
/// spellings rather than one, ranges rather than a `break`, the comment filter first, the
/// indentation rule rather than a brace count) lives there with it. What could not move is the
/// per-crate EVIDENCE that those choices bite HERE, so it is recorded below rather than lost with
/// the copy that used to carry it.
///
/// * **`powi` needs no exemption in this crate.** The shared list bans `powi` because MEASURED on
///   MSVC a `dev` build lowers `llvm.powi` to the CRT's `pow()`, so a crate that has one may need
///   an exemption table of its own. `crates/vike-ml/src` has no `powi` outside a test module to
///   exempt today, which is why this gate carries no such table.
///
/// * **The needle list's three blind spots do not occur here.** `<f64>::exp(x)` (the
///   angle-bracket spelling — the text carries `f64>::exp(`, which neither needle matches),
///   a call reached through a generic bound (`T: Float`), and a call split across two lines by
///   a `max_width` wrap are all invisible to `banned_needles`. None of the three occurs under
///   this crate's `src/` today. A list of spellings is an enumeration and an enumeration is
///   never a proof; this measurement is what stands in for one here, and it has to be retaken
///   the day it stops holding.
///
/// * **The RANGES buy INSURANCE in this crate rather than a fix, and that is the honest answer.**
///   Measured 2026-08-29: every test item under `crates/vike-ml/src` is the last thing in its
///   file, so a `break` at the first marker would change no verdict here today. What the ranges
///   buy is the day somebody splits `gbdt_learner.rs` (1677 lines, with its test module opening at
///   718) and leaves production code below the marker — this gate then does not silently stop
///   reading it while still reporting a confident zero.
///
/// * **The `any(test, …)` spelling is deliberately NOT a range, and this crate is precisely where
///   that matters.** `crates/vike-ml/src/test_support.rs` is gated exactly that way and SHIPS to
///   any consumer enabling `test-support`, so recognising it as a test item would take a shipped
///   module out of this gate's view.
///
/// * **The comment filter has to run FIRST, and this crate holds the prose mention that proves
///   it.** A whole-file `text.find("#[cfg(test)]")` truncates at the first occurrence of that
///   string ANYWHERE, a doc comment included, and a `//`-skipping filter applied afterwards cannot
///   rescue it because it runs on already-truncated text. `gbdt_learner.rs`'s module doc names the
///   attribute in backticks at line 110 — so a whole-file cut would discard 1,567 of that file's
///   1,677 lines and report a confident zero for it.
///
/// * **The indentation rule is exact on this crate's sources.** Verified 2026-08-29: every marker
///   under `crates/vike-ml/src` sits at column 0, so a lone `}` at the item's own indentation is
///   where rustfmt has put the end of every block this gate cuts.
///
/// * **No tree-shaped assertion in this crate could cover the range walk AT ALL**, which is why
///   the walk's proof is a PLANTED FIXTURE and why that fixture moving to
///   `crates/vike-model/tests/libm_walk_selftest.rs` costs this crate nothing it used to have.
///   Because every test item here is the last thing in its file (above), "some production line
///   below a marker was scanned" is FALSE against `crates/vike-ml/src` and could only be written
///   by weakening it into something vacuous. The `unclosed` assertion below is the part of the
///   mechanism this crate CAN still check against its own tree, and it is checked on every run.
#[test]
fn production_code_calls_libm_not_the_platform() {
    let banned = banned_needles();
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let src = root.join("src");
    let mut found = Vec::new();
    let mut scanned: Vec<String> = Vec::new();
    // A test item whose end could not be located swallows the rest of its file exactly the way a
    // `break` would. That is the one QUIET failure of the range walk, so it is collected and
    // asserted rather than absorbed.
    let mut unclosed: Vec<String> = Vec::new();
    let mut stack = vec![src];
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir).expect("crate has a src/ directory") {
            let path = entry.expect("readable dir entry").path();
            if path.is_dir() {
                stack.push(path);
                continue;
            }
            if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                continue;
            }
            // `\` -> `/` so a reported path reads the same on the Windows dev box and on Linux.
            let rel = path.strip_prefix(root).unwrap_or(&path).to_string_lossy().replace('\\', "/");
            let name = path.file_name().unwrap().to_string_lossy().to_string();
            let text = std::fs::read_to_string(&path).expect("readable source file");
            scanned.push(name);
            let lines: Vec<&str> = text.lines().collect();
            let test_items = cfg_test_ranges(&lines);
            for &(start, _, closed) in &test_items {
                if !closed {
                    unclosed.push(format!("  {rel}:{}", start + 1));
                }
            }
            for (i, line) in lines.iter().enumerate() {
                if test_items.iter().any(|&(start, end, _)| i >= start && i < end) {
                    continue; // inside a test item — not shipped
                }
                let code = line.trim_start();
                if code.starts_with("//") {
                    continue; // a doc comment naming `exp` is prose, not a call
                }
                for pat in &banned {
                    if line.contains(pat.as_str()) {
                        found.push(format!("  {rel}:{} {code}", i + 1));
                    }
                }
            }
        }
    }
    // Non-vacuity: an empty `found` is indistinguishable from a scan that opened nothing. The named
    // files are where this gate earns its keep — the converted site, plus the one file whose test
    // module contains the only `sin`/`cos` calls in the crate (so if the range walk ever broke,
    // `gbdt_learner.rs` is where it would report a LOUD false positive rather than a silent miss).
    //
    // ⚠ `metrics.rs` was a third witness here and is DELETED, and it is worth saying how it failed
    // rather than just dropping the name: this assertion is what caught the deletion. The module
    // vanished, the scan quietly found one fewer file, and the loud panic below is the only reason
    // that did not read as a pass. That is the whole argument for naming witnesses by hand — a
    // scan whose input shrinks silently is the failure this pattern exists to make impossible.
    // Do not replace this list with a count; a count is what a deletion trivially satisfies.
    for must in ["infer.rs", "gbdt_learner.rs"] {
        assert!(
            scanned.iter().any(|s| s == must),
            "the scan never opened {must}, so an empty result proves nothing about the files this \
             gate exists for. Scanned {} files.",
            scanned.len()
        );
    }
    assert!(
        unclosed.is_empty(),
        "a test item's closing line could not be located, so everything below it went UNSCANNED — \
         the exact hole a `break` leaves, wearing a different cause. See `cfg_test_ranges`: the end \
         is the item's own indentation followed by a lone `}}`, or a `;` for a `mod NAME;` \
         declaration.\n{}",
        unclosed.join("\n")
    );
    assert!(
        found.is_empty(),
        "production code must call the `libm` CRATE rather than `f64`'s platform-libm methods, so a \
         PROBABILITY out of this crate is a property of the model rather than of the box that ran \
         it. BOTH spellings are banned, `x.exp()` and `f64::exp(x)`: same inherent method, same \
         libcall (see `banned_needles`). `powi` is banned too — on MSVC a `dev` build makes it a \
         `pow()` libcall — and its cure is a MULTIPLICATION rather than `libm` when the base is a \
         literal:\n{}",
        found.join("\n")
    );
}
