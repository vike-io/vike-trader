/// Production code in this crate must reach a transcendental through the `libm` CRATE.
///
/// ⚠ Not redundant with the hash table, which pins TWO functions: a new transcendental in the
/// learner, the importance or the fit cache would be invisible to the corpus above.
///
/// Scope: every `.rs` under `src/`, recursively, MINUS each file's test-item ranges. NO exemptions:
/// the only `vike_model::libm_walk::BANNED_FNS` calls in `crates/vike-ml/src` are inside
/// `gbdt_learner.rs`'s test module (its synthetic `sin`/`cos` feature fixture).
///
/// # What holds on THIS crate
///
/// The text machinery (`banned_needles`, `cfg_test_ranges`) and the GENERAL argument for each of
/// its choices live in `vike_model::libm_walk` (decision 0074). The per-crate evidence:
///
/// * **`powi` needs no exemption here.** It is banned because a MSVC `dev` build lowers
///   `llvm.powi` to the CRT's `pow()`; `crates/vike-ml/src` has none outside a test module.
///
/// * **The needle list's three blind spots do not occur here** — `<f64>::exp(x)` (the text carries
///   `f64>::exp(`, which neither needle matches), a call through a generic bound (`T: Float`), and
///   a call split across two lines by a `max_width` wrap. An enumeration is never a proof; this
///   measurement stands in for one and must be retaken the day it stops holding.
///
/// * **The RANGES are INSURANCE here, not a fix.** Every test item under `crates/vike-ml/src` is
///   the last thing in its file today; the ranges cover the day somebody leaves production code
///   below a marker, so the gate does not silently stop reading it.
///
/// * **The `any(test, …)` spelling is deliberately NOT a range.** `crates/vike-ml/src/seam/test_support.rs`
///   is gated that way and SHIPS to any consumer enabling `test-support`.
///
/// * **The comment filter has to run FIRST.** `gbdt_learner.rs`'s module doc names the
///   `#[cfg(test)]` attribute in backticks, so a whole-file `text.find` cut would discard most of
///   that file and report a confident zero.
///
/// * **The indentation rule is exact here**: every marker under `crates/vike-ml/src` sits at
///   column 0, where rustfmt puts the lone `}` that ends each block this gate cuts.
///
/// * **No tree-shaped assertion here could cover the range walk**, since every test item is last in
///   its file; the walk's proof is the planted fixture in
///   `crates/vike-model/tests/libm_walk_selftest.rs`. The `unclosed` assertion below is the part
///   this crate CAN check against its own tree.
#[test]
fn production_code_calls_libm_not_the_platform() {
    let banned = banned_needles();
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let src = root.join("src");
    let mut found = Vec::new();
    let mut scanned: Vec<String> = Vec::new();
    // A test item whose end could not be located swallows the rest of its file like a `break`:
    // the range walk's one QUIET failure, so it is collected and asserted.
    let mut unclosed: Vec<String> = Vec::new();
    // A file a `#[cfg(test)] mod NAME;` declaration pulls in is test code WHOLE, with no marker
    // inside it for `cfg_test_ranges` to find — skipped before it is read, like any test module.
    let test_files = cfg_test_module_files_under(&src);
    let mut stack = vec![src];
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir).expect("crate has a src/ directory") {
            let path = entry.expect("readable dir entry").path();
            if path.is_dir() {
                stack.push(path);
                continue;
            }
            if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                continue;
            }
            if test_files.contains(&path) {
                continue;
            }
            // `\` -> `/` so a reported path reads the same on the Windows dev box and on Linux.
            let rel = path.strip_prefix(root).unwrap_or(&path).to_string_lossy().replace('\\', "/");
            let name = path.file_name().unwrap().to_string_lossy().to_string();
            let text = std::fs::read_to_string(&path).expect("readable source file");
            scanned.push(name);
            let lines: Vec<&str> = text.lines().collect();
            let test_items = cfg_test_ranges(&lines);
            for &(start, _, closed) in &test_items {
                if !closed {
                    unclosed.push(format!("  {rel}:{}", start + 1));
                }
            }
            for (i, line) in lines.iter().enumerate() {
                if test_items.iter().any(|&(start, end, _)| i >= start && i < end) {
                    continue; // inside a test item — not shipped
                }
                let code = line.trim_start();
                if code.starts_with("//") {
                    continue; // a doc comment naming `exp` is prose, not a call
                }
                for pat in &banned {
                    if line.contains(pat.as_str()) {
                        found.push(format!("  {rel}:{} {code}", i + 1));
                    }
                }
            }
        }
    }
    // Non-vacuity: an empty `found` is indistinguishable from a scan that opened nothing. The
    // witnesses are the converted site and the file whose test module holds the crate's only
    // `sin`/`cos` calls (a broken range walk reports a LOUD false positive there). ⚠ Named by hand
    // on purpose — this assertion caught a deleted witness once; a count is what a deletion
    // trivially satisfies.
    for must in ["infer.rs", "gbdt_learner.rs"] {
        assert!(
            scanned.iter().any(|s| s == must),
            "the scan never opened {must}, so an empty result proves nothing about the files this \
             gate exists for. Scanned {} files.",
            scanned.len()
        );
    }
    assert!(
        unclosed.is_empty(),
        "a test item's closing line could not be located, so everything below it went UNSCANNED — \
         the exact hole a `break` leaves, wearing a different cause. See `cfg_test_ranges`: the end \
         is the item's own indentation followed by a lone `}}`, or a `;` for a `mod NAME;` \
         declaration.\n{}",
        unclosed.join("\n")
    );
    assert!(
        found.is_empty(),
        "production code must call the `libm` CRATE rather than `f64`'s platform-libm methods, so a \
         PROBABILITY out of this crate is a property of the model rather than of the box that ran \
         it. BOTH spellings are banned, `x.exp()` and `f64::exp(x)`: same inherent method, same \
         libcall (see `banned_needles`). `powi` is banned too — on MSVC a `dev` build makes it a \
         `pow()` libcall — and its cure is a MULTIPLICATION rather than `libm` when the base is a \
         literal:\n{}",
        found.join("\n")
    );
}
