//! The generated `$OUT_DIR/buildinfo.rs`, written as ONE template of the file it produces.

use super::{FROZEN, UNKNOWN, iso8601_utc};

/// The generated `$OUT_DIR/buildinfo.rs`, as text.
///
/// Every string is written through `{:?}` — `Debug for str`, i.e. a valid Rust string literal with
/// quotes and backslashes escaped. Not optional: this is generated code, and a branch name or a
/// vendor's `rustc --version` banner may contain anything.
pub(super) fn render(
    sha: &str,
    dirty: Option<bool>,
    epoch_secs: u64,
    rustc_version: &str,
    target: &str,
    profile: &str,
) -> String {
    let timestamp = iso8601_utc(epoch_secs);
    format!(
        r"// @generated by crates/vike-buildinfo/build.rs — do not edit.
/// What an unresolved fact reports: no `git` on the box, no repository (a source
/// tarball), or a `rustc --version` that would not run.
pub const UNKNOWN: &str = {UNKNOWN:?};
/// What a FROZEN debug build reports instead of a commit: CI's
/// `VIKE_BUILDINFO_FREEZE=1`, which a release build ignores. Never a sha, never
/// [`UNKNOWN`] — `crates/vike-buildinfo/build.rs`'s module doc is the argument.
pub const FROZEN: &str = {FROZEN:?};
/// The short git commit this binary was built from, [`UNKNOWN`], or [`FROZEN`].
pub const GIT_SHA: &str = {sha:?};
/// Whether the working tree carried uncommitted changes; `None` when that could
/// not be established — a [`FROZEN`] build never asks. See [`git_state`] for the
/// rendering.
pub const GIT_DIRTY: Option<bool> = {dirty:?};
/// When this binary was built, as seconds since the Unix epoch; `0` in a [`FROZEN`]
/// build, so its bytes are the same on every runner.
pub const BUILD_EPOCH_SECS: u64 = {epoch_secs};
/// When this binary was built: RFC-3339 UTC, second resolution.
pub const BUILD_TIMESTAMP: &str = {timestamp:?};
/// `rustc --version` of the compiler that built this, or [`UNKNOWN`].
pub const RUSTC_VERSION: &str = {rustc_version:?};
/// The target triple this was compiled for, or [`UNKNOWN`].
pub const TARGET: &str = {target:?};
/// The cargo profile this was compiled under: `debug` or `release`.
pub const PROFILE: &str = {profile:?};
"
    )
}
