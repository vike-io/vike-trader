/// Production code in this crate must reach a transcendental through the `libm` CRATE.
///
/// ⚠ Not redundant with the hash table. That table pins TWO functions; this crate is the workspace
/// vocabulary — every venue, every strategy and every engine reads its types — and a new
/// transcendental in any of its other files would be invisible to the corpus while making a shared
/// primitive depend on which box ran it.
///
/// The text machinery this gate walks with — `banned_needles` and `cfg_test_ranges` — is
/// `vike_model::libm_walk`, shared with the ten sibling probes under decision 0074, and that
/// module's doc carries the general argument for each piece. What stays here is the half that is a
/// fact about THIS crate, measured rather than assumed.
///
/// Scope: every `.rs` under `src/`, recursively, MINUS each file's test-item ranges. There are NO
/// exemptions and there should not need to be: measured 2026-08-29, `crates/vike-model/src`
/// contains not one call to any banned name outside a test item, so this gate starts at a clean
/// zero rather than at a grandfathered list. That includes `powi`, which in this crate is the
/// FINDING rather than a precaution: `crates/vike-model/src/strategy/maker_params.rs`'s
/// `ladder_size_mult` is the one site in the workspace's `powi` census where the two platforms
/// actually disagreed, and the module doc above carries the two hashes it disagreed by. Where a
/// base is the literal 10 or 2 the cure is a MULTIPLICATION rather than `libm::pow`, which is why
/// a sibling crate may carry a `powi` exemption table — `crates/vike-model/src` has no such site
/// to exempt today. `sqrt`, by contrast, is on no banned list at all, and `fair::p_up`'s own
/// `.sqrt()` is exactly the case that makes the omission right: IEEE 754 requires it correctly
/// rounded, so there is nothing to convert it TO, and that function's comment says so.
///
/// ⚠ **What the needle list cannot see, under THIS crate's sources.** `vike_model::libm_walk`
/// declares three spellings it misses — `<f64>::exp(x)` (the angle-bracket form: `f64>::exp(` is
/// what appears, and no needle ends in `>`), a call reached through a generic bound (`T: Float`),
/// and a call split across two lines by a `max_width` wrap — and states that whether any of them
/// OCCURS is a per-crate fact belonging to each gate. It is stated here: none of the three occurs
/// under `crates/vike-model/src` today. A list of spellings is an enumeration, and an enumeration
/// is never a proof.
///
/// ⚠ **Why the walk takes RANGES rather than stopping at the first marker — in this crate a live
/// difference rather than insurance.** A `break` says "the shipped half of a file ends at its
/// first test module", which holds only when that module is LAST. Measured 2026-08-29 over
/// `crates/vike-model/src`: `strategy/maker_params.rs` carries 180 production lines below its
/// first marker (three test modules, the first at line 372 of 1045 — `HorizonMode`, `KappaMode`
/// and the toxicity bag all live below it) and `strategy/mod.rs` carries 42. A `break` would hand
/// this gate a confident zero over a fifth of the file that defines the maker's own parameter
/// vocabulary.
///
/// ⚠ **`#[cfg(any(test, feature = "…"))]` is deliberately NOT cut, and this crate holds the
/// workspace's clearest reason.** `crates/vike-model/src/strategy/mod.rs`'s `MockBroker` wears
/// exactly that attribute and is compiled into any consumer enabling `test-support`, so it SHIPS.
/// Treating it as test-only would take a shipped double out of this gate's view.
///
/// ⚠ **The comment filter runs line by line and BEFORE the marker match, and this crate is one of
/// the trees that proves why.** A whole-file `text.find("#[cfg(test)]")` truncates at the first
/// occurrence of that string ANYWHERE, a doc comment included, and a `//`-skipping filter applied
/// afterwards cannot rescue it because it runs on already-truncated text. This crate carries four
/// such prose mentions today (`change_journal.rs` has three, `venue_margin_support.rs` one), so a
/// whole-file cut would blank most of `change_journal.rs` and report a confident zero for it.
///
/// ⚠ **An item's end is found by INDENTATION, and that is exact here for a structural reason.**
/// `cargo fmt --check` is CI's first gate, so every file in the tree is rustfmt output and rustfmt
/// closes a block with a `}` alone on a line at the block's OWN indentation. Verified over this
/// crate 2026-08-29: every marker under `crates/vike-model/src` sits at column 0.
///
/// ⚠ **`scanned_past_a_test_module` below is evidence about TODAY'S files, not about the
/// mechanism.** It is real, but it is real about `maker_params.rs` and `strategy/mod.rs` AS THEY
/// ARE — reorganise either so its test modules go last and that assertion passes vacuously while
/// the range walk itself goes unproven. The mechanism is held by a planted synthetic fixture
/// instead, one copy for all eleven probes, and it lives in this crate rather than a stranger's:
/// `crates/vike-model/tests/libm_walk_selftest.rs`.
#[test]
fn production_code_calls_libm_not_the_platform() {
    let banned = banned_needles();
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let src = root.join("src");
    let mut found = Vec::new();
    let mut scanned: Vec<String> = Vec::new();
    // Files where at least one NON-BLANK production line BELOW the first marker was scanned — the
    // property a `break` makes impossible. ⚠ Non-blank matters: two adjacent test modules are
    // separated by an empty line, and counting that line would make this assertion pass on files
    // that carry no production code below a marker at all.
    let mut scanned_past_a_test_module: Vec<String> = Vec::new();
    // A test item whose end could not be located swallows the rest of its file exactly the way a
    // `break` would. That is the one QUIET failure of the range walk, so it is collected and
    // asserted rather than absorbed.
    let mut unclosed: Vec<String> = Vec::new();
    let mut stack = vec![src];
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir).expect("crate has a src/ directory") {
            let path = entry.expect("readable dir entry").path();
            if path.is_dir() {
                stack.push(path);
                continue;
            }
            if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                continue;
            }
            // `\` -> `/` so a reported path reads the same on the Windows dev box and on Linux.
            let rel = path.strip_prefix(root).unwrap_or(&path).to_string_lossy().replace('\\', "/");
            let name = path.file_name().unwrap().to_string_lossy().to_string();
            let text = std::fs::read_to_string(&path).expect("readable source file");
            scanned.push(name.clone());
            let lines: Vec<&str> = text.lines().collect();
            let test_items = cfg_test_ranges(&lines);
            for &(start, _, closed) in &test_items {
                if !closed {
                    unclosed.push(format!("  {rel}:{}", start + 1));
                }
            }
            let first_marker = test_items.first().map(|&(start, _, _)| start);
            for (i, line) in lines.iter().enumerate() {
                if test_items.iter().any(|&(start, end, _)| i >= start && i < end) {
                    continue; // inside a test item — not shipped
                }
                let code = line.trim_start();
                if code.starts_with("//") {
                    continue; // a doc comment naming `exp` is prose, not a call
                }
                if !code.is_empty()
                    && first_marker.is_some_and(|m| i > m)
                    && !scanned_past_a_test_module.contains(&name)
                {
                    scanned_past_a_test_module.push(name.clone());
                }
                for pat in &banned {
                    if line.contains(pat.as_str()) {
                        found.push(format!("  {rel}:{} {code}", i + 1));
                    }
                }
            }
        }
    }
    // Non-vacuity, aimed at the failure this scan is most likely to have: `src/` NESTS here
    // (`strategy/`), so a walk that stopped at the top level would still open ~45 files and report
    // a confident zero while never reading `maker_params.rs` — the one file with a MEASURED
    // cross-platform divergence in its history.
    for must in ["fair.rs", "maker_params.rs", "scalar.rs"] {
        assert!(
            scanned.iter().any(|s| s == must),
            "the scan never opened {must}, so an empty result proves nothing about the files this \
             gate exists for. Scanned {} files.",
            scanned.len()
        );
    }
    assert!(
        unclosed.is_empty(),
        "a test item's closing line could not be located, so everything below it went UNSCANNED — \
         the exact hole a `break` leaves, wearing a different cause. See `cfg_test_ranges`: the end \
         is the item's own indentation followed by a lone `}}`, or a `;` for a `mod NAME;` \
         declaration.\n{}",
        unclosed.join("\n")
    );
    // The non-vacuity assertion for the RANGE walk, and the one a `break` could not pass. Both
    // files named carry real production code BELOW a test module — measured 2026-08-29 at 180 and
    // 42 non-blank lines. If this goes red, the walk has reverted to treating the first marker as
    // the end of the shipped file.
    for must in ["maker_params.rs", "mod.rs"] {
        assert!(
            scanned_past_a_test_module.iter().any(|s| s == must),
            "no production line below {must}'s first test marker was scanned, so this gate has \
             gone blind to the region below every mid-file test module — which in this crate is \
             where `HorizonMode`, `KappaMode` and `MockBroker` live. Scanned past a test module: \
             {scanned_past_a_test_module:?}"
        );
    }
    assert!(
        found.is_empty(),
        "production code must call the `libm` CRATE rather than `f64`'s platform-libm methods, so a \
         POSTED QUOTE (`fair::p_up`) and an ORDER SIZE (`maker_params::ladder_size_mult`) do not \
         depend on which box computed them. BOTH spellings are banned, `x.exp()` and `f64::exp(x)`: \
         same inherent method, same libcall (see `banned_needles`). `powi` is banned too, and in \
         this crate that is the MEASURED case rather than a precaution — `ladder_size_mult` hashed \
         differently on MSVC and glibc as `ratio.powi(k)`. Where a base is the literal 10 or 2 the \
         cure is a MULTIPLICATION rather than `libm`; where it is a runtime f64 the cure is \
         `libm::pow`:\n{}",
        found.join("\n")
    );
}
