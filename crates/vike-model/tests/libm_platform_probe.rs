//! The cross-platform PIN for this crate's two transcendental sites — the gate `vike-indicators`,
//! `vike-analytics` and `vike-mm` each carry, and which vike-model's conversions landed WITHOUT.
//!
//! IEEE 754 requires `+ - * /` and `sqrt` to be correctly rounded and requires NOTHING of
//! `ln`/`exp`/`pow`, so an `f64` METHOD call reaches whichever libm the PLATFORM ships — MSVC's CRT
//! on the Windows dev box, glibc on the the CI box Linux boxes and every CI runner — and the two
//! disagree in the last bit.
//! `docs/decisions/0032-transcendentals-come-from-the-libm-crate-not-the-platform.md` is the
//! accepted verdict; both sites below already route through the `libm` CRATE, and until this file
//! existed nothing in the tree would have noticed the next edit moving either one back.
//!
//! # Why this crate is pinned ahead of most of the tree, in one line each
//!
//! * **`fair::p_up` reaches a POSTED QUOTE**, through four quantisers, none of which absorbs a last
//!   bit. Its own doc enumerates them and this file does not restate the argument — read it there
//!   (`crates/vike-model/src/fair.rs`'s `p_up`). The short version: a tick-snapped price, a
//!   quote-or-no-quote straddle guard, a strict-`<` argmin over the beta set, and a strict-`>`
//!   entry gate whose 1-ulp sensitivity is ALREADY a pinned property elsewhere
//!   (`crates/vike-strategy/src/fair_value.rs` builds `f64::from_bits(e.to_bits() - 1)` to prove it).
//! * **`strategy::maker_params::ladder_size_mult` produces an ORDER QUANTITY**, and it is the one
//!   site in this workspace's `powi` census where the `libm` substitution was actually NEEDED —
//!   measured, `ratio.powi(k)` hashed `e77cac46a86678b1` on Windows/MSVC `dev` and
//!   `c42a98c72a627fca` on Linux/glibc `dev` over 500 ratios × 12 rungs. Two boxes running one
//!   ladder sized its rungs differently. That measurement is on the function's own doc; the row
//!   below is what stops it coming back.
//!
//! # ⚠ The corpus is PURE ARITHMETIC, and that is load-bearing
//!
//! Every input is generated by an integer LCG plus `+ - * /`, never by `.sin()`/`.cos()`. Those are
//! themselves platform-dependent (MEASURED — `crates/vike-analytics/tests/libm_platform_probe.rs`'s
//! Part A sweeps them as its own control), so generating inputs with them would make every row here
//! diverge because of the INPUTS rather than because of the function under test: a false positive
//! that reads exactly like a real one.
//!
//! # ⚠ One row is a CONTROL and must never be deleted as redundant
//!
//! `LadderParams::rungs Linear` calls no transcendental at all — it is `+`, `-` and `*`, every one
//! correctly rounded by IEEE 754 — so it is IDENTICAL on both boxes by construction. That is
//! exactly why it is here. It draws from the same LCG corpus as the `Geometric` row, so if the two
//! boxes ever disagree about IT, the divergence is in the INPUTS or in this harness and every other
//! row's verdict is void. The analytics twin makes the same point about its two agreeing rows: they
//! "are what made the other seven a finding rather than a broken harness".
//!
//! ```text
//! <cargo> test -p vike-model --test libm_platform_probe
//! ```

