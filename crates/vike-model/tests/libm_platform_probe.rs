/// A ladder spec whose only varying parts are the ones `ladder_size_mult` reads.
///
/// `offset_step`/`offset_unit` are held fixed on purpose: they feed the rung OFFSET, which is plain
/// multiplication, and varying them would add distinct values to the hash that have nothing to do
/// with the site under test — inflating `distinct` into a number that no longer evidences the
/// `pow` being exercised.
fn ladder(profile: LadderSizeProfile, ratio: f64, levels: usize) -> LadderParams {
    LadderParams {
        levels,
        offset_step: 1.0,
        offset_unit: LadderOffsetUnit::HalfSpread,
        size_profile: profile,
        size_ratio: ratio,
    }
}

/// Every covered function, folded over its own corpus.
///
/// Returns rows in a FIXED order; [`PLATFORM_INVARIANT`] is compared positionally, so a reordering
/// is a re-record rather than a silent re-pairing.
fn production_rows() -> Vec<Row> {
    let mut out = Vec::new();

    // --- fair::p_up — `libm::log(s_now / s_open)` then `libm::erf(x / SQRT_2)`.
    //
    // The domain is the one the cheap_np taker and the Avellaneda-Stoikov maker actually occupy: a
    // spot ratio close to 1 (a five-minute window's move is basis points, not multiples), a
    // per-SECOND log-return sigma, and `t` strictly inside `[0, h)`. A wide ratio sweep would spend
    // most of the corpus on `p_up` values saturated at 0 or 1, where the `erf` is flat and a last
    // bit in the `log` cannot survive to the output — the row would then be dominated by samples
    // that CANNOT report a divergence, which is a quieter version of vacuity.
    //
    // ⚠ `t` is kept strictly below `h` for the corresponding reason: at `t == h` the `max(h - t,
    // 1e-9)` floor pins `denom` to one value and the row would pin the floor instead of the maths.
    // One in eight samples deliberately lands in the last instant of the window anyway, because
    // that IS where a live maker quotes hardest and the floor's behaviour is worth pinning too.
    {
        let mut s = 0x1234_5678_9abc_def0u64;
        let mut vals = Vec::with_capacity(SAMPLES);
        for i in 0..SAMPLES {
            let beta = 0.05 + lcg(&mut s) * 3.0;
            let s_open = 100.0 + lcg(&mut s) * 60_000.0;
            // ±2% around the open — the range a five-minute crypto window actually moves in.
            let s_now = s_open * (0.98 + lcg(&mut s) * 0.04);
            let sigma = 1e-6 + lcg(&mut s) * 3e-3;
            let h = 60.0 + lcg(&mut s) * 540.0;
            let t = if i % 8 == 0 { h } else { lcg(&mut s) * h * 0.999 };
            vals.push(p_up(beta, s_now, s_open, sigma, t, h));
        }
        out.push(finish("fair::p_up (log + erf)", &vals));
    }

    // --- strategy::maker_params::ladder_size_mult, Geometric — `libm::pow(ratio, k as f64)`.
    //
    // ⚠ Driven through the PUBLIC `LadderParams::rungs` rather than by making the private
    // `ladder_size_mult` reachable. That is the stronger pin as well as the less invasive one: what
    // a maker rests is the `Vec<LadderLevel>` this returns, so the row covers the `max(0.0)` floor
    // and the level-0 special case alongside the power.
    //
    // The ratio sweep straddles 1.0 — `(0.35, 1.0)` decays deeper rungs, `(1.0, 3.35)` grows them —
    // because both are configurations an operator writes and `pow` behaves differently on either
    // side of 1. A ratio of EXACTLY 1.0 is not excluded but is measure-zero in this generator, and
    // it is the one value where the site is portable by accident (`pow(1, y)` is an exact special
    // case in C99 Annex F), so a corpus that landed on it often would overstate the pin.
    {
        let mut s = 0x0fed_cba9_8765_4321u64;
        let mut vals = Vec::with_capacity(SAMPLES);
        while vals.len() < SAMPLES {
            let ratio = 0.35 + lcg(&mut s) * 3.0;
            let levels = 2 + (lcg(&mut s) * 30.0) as usize;
            for rung in ladder(LadderSizeProfile::Geometric, ratio, levels).rungs() {
                vals.push(rung.size);
            }
        }
        vals.truncate(SAMPLES);
        out.push(finish("maker_params::rungs Geometric (pow)", &vals));
    }

    // --- The CONTROL. `Linear` is `1.0 + k·(ratio − 1.0)` — `+`, `-`, `*` only, every one
    // correctly rounded by IEEE 754 — so it is bit-identical on both platforms BY CONSTRUCTION.
    //
    // ⚠ Do not delete this row as "pinning nothing". It draws from the same LCG corpus as the
    // `Geometric` row above, so it is the arm that distinguishes "the FUNCTION diverged" from "the
    // INPUTS diverged, or this harness is broken". If it ever goes red, no other row in this file
    // means anything until that is explained.
    {
        let mut s = 0x0fed_cba9_8765_4321u64;
        let mut vals = Vec::with_capacity(SAMPLES);
        while vals.len() < SAMPLES {
            let ratio = 0.35 + lcg(&mut s) * 3.0;
            let levels = 2 + (lcg(&mut s) * 30.0) as usize;
            for rung in ladder(LadderSizeProfile::Linear, ratio, levels).rungs() {
                vals.push(rung.size);
            }
        }
        vals.truncate(SAMPLES);
        out.push(finish("maker_params::rungs Linear (CONTROL, no transcendental)", &vals));
    }

    out
}

/// ⚠ **ONE set of constants for EVERY platform — that is the entire claim.**
///
/// ⚠ **Every hash below is the literal `"RECORD"`, a PLACEHOLDER that fails by construction, and
/// that is deliberate.** The convention is the analytics twin's
/// (`crates/vike-analytics/tests/libm_platform_probe.rs`'s `PLATFORM_INVARIANT`): rows are
/// sometimes written on a box that cannot run cargo, and a plausible-looking hex literal invented
/// there is INDISTINGUISHABLE from a recorded one while pinning nothing — the single worst outcome
/// available here. `"RECORD"` cannot match any FNV output, so
/// [`converted_functions_are_platform_invariant`] stays red until a human RUNS this file on
/// Linux/glibc AND on Windows/MSVC, confirms the two runs agree bit-for-bit, and pastes the agreed
/// hash in. **A red row spelled `"RECORD"` is an UNFINISHED RECORDING, not a regression.**
///
/// ⚠ **Re-record by RUNNING, never by editing a digit**, and never from ONE box. If a recorded row
/// later goes red the question is which platform moved and why:
///   (a) an intended numeric change — re-record on both boxes and pin the hash they AGREE on; or
///   (b) a call site went back to the platform's libm, in which case the two boxes will NOT agree
///       and the fix is in the source, not here.
///
/// ⚠ **A per-platform table (`#[cfg(windows)]` / `#[cfg(unix)]`) is NOT a repair and must never be
/// added.** It would make the gate green by asserting the divergence was intended — the one
/// conclusion the `ladder_size_mult` measurement refutes.
const PLATFORM_INVARIANT: [(&str, &str); 3] = [
    ("fair::p_up (log + erf)", "4c0ac43bde5de02f"),
    ("maker_params::rungs Geometric (pow)", "0348c8e24f96128d"),
    ("maker_params::rungs Linear (CONTROL, no transcendental)", "183352c7d3052e6f"),
];

/// The cross-platform proof, as a GATE rather than a diff somebody has to remember to run.
///
/// NOT `#[ignore]`d: CI runs it on Linux every PR and `just t vike-model` runs it on the Windows
/// dev box, both against the same committed table.
#[test]
fn converted_functions_are_platform_invariant() {
    let got = production_rows();
    assert_eq!(
        got.len(),
        PLATFORM_INVARIANT.len(),
        "row count drifted from PLATFORM_INVARIANT — it must be re-recorded"
    );

    let mut bad = Vec::new();
    for (r, (want_label, want_hash)) in got.iter().zip(PLATFORM_INVARIANT.iter()) {
        assert_eq!(&r.label, want_label, "row ORDER drifted — the compare is positional");
        if r.hash != *want_hash {
            bad.push(format!("  {:<56} want={want_hash} got={}", r.label, r.hash));
        }
    }

    // The non-vacuity half is asserted BEFORE the hashes, deliberately: a thin row is a defect
    // whether or not its hash matched, and an author re-recording a `"RECORD"` row must be told
    // about it BEFORE pasting a hash that would pin nothing.
    let thin: Vec<String> = got
        .iter()
        .filter(|r| r.distinct < MIN_DISTINCT)
        .map(|r| format!("  {:<56} {} distinct finite of {} samples", r.label, r.distinct, r.n))
        .collect();
    assert!(
        thin.is_empty(),
        "a pinned row's corpus is too thin to detect a last-bit divergence: it would hash \
         identically on every platform and read as a PASS while proving nothing. WIDEN the input \
         ranges — never lower MIN_DISTINCT ({MIN_DISTINCT}):\n{}",
        thin.join("\n")
    );

    if !bad.is_empty() {
        let paste: String =
            got.iter().map(|r| format!("    (\"{}\", \"{}\"),\n", r.label, r.hash)).collect();
        panic!(
            "\nvike-model output moved away from the platform pin:\n{}\n\n\
             There is no tolerance here to widen, and hand-editing a digit defeats the gate.\n\
             A moved `p_up` is a moved QUOTE and a moved `rungs Geometric` is a moved ORDER SIZE.\n\
             If the want= column reads RECORD this is an UNFINISHED RECORDING rather than a\n\
             regression: run this file on BOTH Windows and Linux, confirm they agree, paste.\n\
             ⚠ If the CONTROL row moved, stop: the corpus or this harness is broken and no other\n\
             row's verdict means anything.\n\n\
             const PLATFORM_INVARIANT: [(&str, &str); {}] = [\n{paste}];\n",
            bad.join("\n"),
            got.len(),
        );
    }
}

/// The control arm for the non-vacuity threshold itself.
///
/// ⚠ Without this, `MIN_DISTINCT` is an assertion nobody has checked DISCRIMINATES. A `distinct`
/// computation that counted samples rather than distinct values — or a threshold accidentally set
/// to `0` — would pass every row above while the guard did nothing, and catching a check that
/// passes while doing nothing is the guard's entire job.
#[test]
fn the_non_vacuity_check_discriminates() {
    let constant: Vec<f64> = (0..SAMPLES).map(|_| 0.5f64).collect();
    assert!(
        finish("control::constant", &constant).distinct < MIN_DISTINCT,
        "the non-vacuity check does not discriminate: a constant series passed it"
    );
    assert_eq!(
        finish("control::nan", &(0..SAMPLES).map(|_| f64::NAN).collect::<Vec<f64>>()).distinct,
        0,
        "an all-NaN row must report ZERO distinct FINITE values — the analytics twin's vacuous row \
         was all-NaN rather than constant, and a `distinct` that counted NaNs would have passed it"
    );
    let mut s = 0xdead_beef_cafe_babeu64;
    let rich: Vec<f64> = (0..SAMPLES).map(|_| lcg(&mut s)).collect();
    assert!(
        finish("control::rich", &rich).distinct >= MIN_DISTINCT,
        "the corpus generator itself is degenerate — every row above is void"
    );
}

