// The hashing/corpus machinery. Deliberately a per-crate COPY: decision 0074 moved only the TEXT
// parser into `vike_model::libm_walk`, because a parser takes lines and returns ranges and can be
// moved out from under nobody — while a corpus IS this crate's rows and stays with them.
