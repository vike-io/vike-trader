//! **No order vanishes over the hop** (wave 2, W19; B.7, the contract in `vike-gatewayhub-client`'s `trade`
//! module doc, line one): random interleavings of submit, cancel and modify with link cuts and heals,
//! gatewayhub restarts and a takeover, against the REAL client, a REAL gatewayhub server and a scripted
//! venue that outlives the daemon (`tests/support/hop_rig.rs`).
//!
//! After every interleaving the link is healed, the tradehub does what its composition does after a
//! reconnect (starts the adapter again, asks the daemon to resolve what stayed UNKNOWN), every order the
//! core has no terminal for is cancelled, and the books are checked against what the VENUE saw:
//!
//! 1. **never twice**: an order has at most one LIVE terminal event. A lookup by client order id
//!    (`confirm`, which the daemon runs for an UNKNOWN submit after an epoch change) RE-STATES a terminal the
//!    venue may already have sent live, as an ordinary event under the next `seq`; the venue's lookup marks
//!    its copy ([`hop_rig::is_restated`]), at most as many of them may reach the lane as the venue answered
//!    lookups, and the core folds one as a no-op (`the_core_folds_a_restated_terminal_once` in
//!    `hop_kill_proofs.rs`);
//! 2. **never a phantom**: an order the client or the daemon rejected on its own account (NEVER-SENT,
//!    NEVER-RECEIVED, lease closed, no adapter) was never seen by the venue; the venue here refuses nothing,
//!    so ANY reject proves the order was not sent;
//! 3. **never nothing**: every submit was seen by the venue, or was rejected, or is named by
//!    `unknown_orders()`: the accounting identity of a lossy link;
//! 4. **it ends** (while the lease is open): after the sweep every order has a terminal event, or is named
//!    UNKNOWN. (A lease closed for good by a takeover can no longer cancel; 1 to 3 still hold for it.) One
//!    exception, by design: an order the VENUE ended while the daemon that would have relayed it died (a
//!    cancel written just before a restart) stays `Accepted` for the client, which is told "unknown order" by
//!    its sweep; a lost cancel's outcome is reconcile's (`directed_a_cancel_the_dying_daemon_never_relayed`).
//!
//! The ops are generated by `proptest`; a counterexample is committed BESIDE this file, as the file
//! crates/vike-tradehub/tests/no_order_vanishes.proptest-regressions (written without backticks: it does not
//! exist until a counterexample does). A handful of directed interleavings run the same check
//! without randomness, so the interesting orderings are always exercised and a failure names its ops.

