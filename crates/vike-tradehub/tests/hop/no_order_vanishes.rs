/// One step of an interleaving.
#[derive(Debug, Clone)]
enum Op {
    /// Submit a new order.
    Submit,
    /// Cancel the `n`th submitted order (modulo how many there are).
    Cancel(usize),
    /// Reprice the `n`th submitted order.
    Modify(usize),
    /// Cut the link (every connection dies, new ones are refused).
    Cut,
    /// Let the link back in.
    Heal,
    /// Restart the gatewayhub (a new epoch, nothing in its memory).
    Restart,
    /// Another tradehub takes the lease over, explicitly.
    Takeover,
    /// Let things settle for a moment.
    Pause,
    /// **An account becomes active while the node runs** (decision 0169, slice S1): a SECOND account of the
    /// venue opens its own lease and starts its adapter, in the middle of whatever the link is doing. It
    /// trades nothing; what it must not do is disturb the first account's four rules. Refused while the link is
    /// cut, like a takeover.
    AddAccount,
    /// **The account is stopped again** (decision 0169, slice S2): the added account's lease is detached the way
    /// a stop detaches it, in the middle of whatever the link is doing, and a later `AddAccount` starts it again
    /// (a new lease under the same key). Nothing happens if no account was added. It must disturb none of the
    /// first account's orders, and the lease it closes must be free to open again.
    RemoveAccount,
    /// **A cancel nobody hears** (directed tests only, in no strategy): the venue ends the `n`th order while
    /// the daemon that would have relayed the ending is gone, the race a cancel written just before a restart
    /// runs.
    VenueEndsUnheard(usize),
}

/// Link chaos and submits: cuts, heals, gatewayhub restarts and a takeover between submits.
fn op_chaos() -> impl Strategy<Value = Op> {
    prop_oneof![
        6 => Just(Op::Submit),
        2 => Just(Op::Cut),
        2 => Just(Op::Heal),
        1 => Just(Op::Restart),
        1 => Just(Op::Takeover),
        1 => Just(Op::AddAccount),
        1 => Just(Op::RemoveAccount),
        2 => Just(Op::Pause),
    ]
}

/// The same, with cancels and modifies of earlier orders in the mix (the interleaving that found W19-D2, fixed).
fn op_with_edits() -> impl Strategy<Value = Op> {
    prop_oneof![
        5 => Just(Op::Submit),
        2 => (0_usize..8).prop_map(Op::Cancel),
        1 => (0_usize..8).prop_map(Op::Modify),
        2 => Just(Op::Cut),
        2 => Just(Op::Heal),
        1 => Just(Op::Restart),
        1 => Just(Op::Takeover),
        1 => Just(Op::AddAccount),
        1 => Just(Op::RemoveAccount),
        2 => Just(Op::Pause),
    ]
}

const SETTLE: Duration = Duration::from_secs(10);

thread_local! {
    /// Every message the lane received, in arrival order, with the poll that picked it up (printed on a failure).
    static TRACE: std::cell::RefCell<(Option<std::time::Instant>, Vec<String>)> =
        const { std::cell::RefCell::new((None, Vec::new())) };
}

/// Note a marker line (a step of the script) in the trace.
fn mark(line: String) {
    TRACE.with(|t| {
        let mut t = t.borrow_mut();
        let at = t.0.get_or_insert_with(std::time::Instant::now).elapsed().as_millis();
        t.1.push(format!("{at:>6}ms == {line}"));
    });
}

fn events_of(
    lane: &mut vike_gatewayhub_client::test_support::fake_trade_peer::Lane,
    into: &mut Vec<Event>,
) {
    for ing in lane.drain() {
        TRACE.with(|t| {
            let mut t = t.borrow_mut();
            let at = t.0.get_or_insert_with(std::time::Instant::now).elapsed().as_millis();
            t.1.push(format!("{at:>6}ms {ing:?}"));
        });
        if let Some(e) = ing.venue_event() {
            into.push(e.clone());
        }
    }
}

/// Every terminal event the lane carried for `order_client_id`, a lookup's re-statement included.
fn terminals(events: &[Event], order_client_id: &str) -> usize {
    events
        .iter()
        .filter(|e| order_client_id_of(e) == Some(order_client_id) && is_terminal(e))
        .count()
}

/// The terminals the lane carried for `order_client_id` that are NOT a lookup's re-statement: the venue's own, live.
fn live_terminals(events: &[Event], order_client_id: &str) -> usize {
    events
        .iter()
        .filter(|e| {
            order_client_id_of(e) == Some(order_client_id) && is_terminal(e) && !is_restated(e)
        })
        .count()
}

/// The terminals the lane carried for `order_client_id` that a lookup (`confirm`) re-stated.
fn restated_terminals(events: &[Event], order_client_id: &str) -> usize {
    events
        .iter()
        .filter(|e| {
            order_client_id_of(e) == Some(order_client_id) && is_terminal(e) && is_restated(e)
        })
        .count()
}

/// Whether the venue refused a cancel of `order_client_id` (a non-terminal advisory).
fn cancel_refused(events: &[Event], order_client_id: &str) -> bool {
    events
        .iter()
        .any(|e| matches!(e, Event::OrderCancelRejected(r) if r.order_client_id == order_client_id))
}

fn rejected(events: &[Event], order_client_id: &str) -> bool {
    events
        .iter()
        .any(|e| matches!(e, Event::OrderRejected(r) if r.order_client_id == order_client_id))
}

/// Start the adapter until the daemon ANSWERS (`Some`) or the lease is closed for good (`None`). A question lost
/// with the link says nothing about the lease: `Up` is stale until the link thread has read a cut's end or a
/// takeover's goodbye, and a starved heartbeat is a flap. An old holder answers nothing after a takeover's open
/// has returned, so an answer is a lease that is up NOW.
fn start_until_answered(session: &TradeLease) -> Result<Option<AdapterReply>, String> {
    let mut answer = None;
    let settled = wait_until(SETTLE, || {
        if session.closed_reason().is_none() && session.link_state() == TradeLinkState::Up {
            answer = session.start_adapter(start_args()).ok();
        }
        answer.is_some() || session.closed_reason().is_some()
    });
    if settled {
        Ok(answer)
    } else {
        Err(format!(
            "the adapter never answered and the lease did not close: {:?}",
            session.stats()
        ))
    }
}

/// Run one interleaving and check the four rules. `Err` names the rule and the evidence.
fn run_case(ops: &[Op]) -> Result<(), String> {
    run_case_on(World::new(), ops)
}

/// [`run_case`] over a venue the test scripted.
fn run_case_on(world: Arc<World>, ops: &[Op]) -> Result<(), String> {
    // Declared first, dropped last: the session and the taker end before the daemon goes.
    let mut hop = Hop::start(world, arming(false));
    let (events, mut lane) = poll_lane();
    let session: TradeLease =
        TradeLeaseBuilder::new(hop.link(), account("prop-client"), events.clone())
            .with_timings(fast_trade_timings())
            .open()
            .map_err(|e| format!("the first lease did not open: {e:?}"))?;
    match start_until_answered(&session)? {
        Some(AdapterReply::Running { .. }) => {}
        other => return Err(format!("the adapter did not start: {other:?}")),
    }
    let mut exec = session.execution_client();
    let mut submitted: Vec<String> = Vec::new();
    let mut taker: Option<TradeLease> = None;
    let mut added: Option<TradeLease> = None;
    let mut got: Vec<Event> = Vec::new();

    TRACE.with(|t| *t.borrow_mut() = (Some(std::time::Instant::now()), Vec::new()));
    for step in ops {
        mark(format!("step {step:?}"));
        match step {
            Op::Submit => {
                let order_client_id = format!("s{}", submitted.len());
                exec.submit(&order(&order_client_id, 100.0 + submitted.len() as f64));
                submitted.push(order_client_id);
            }
            Op::Cancel(n) => {
                if !submitted.is_empty() {
                    exec.cancel(&submitted[n % submitted.len()]);
                }
            }
            Op::Modify(n) => {
                if !submitted.is_empty() {
                    let order_client_id = &submitted[n % submitted.len()];
                    exec.modify(&order(order_client_id, 100.0), None, Some(99.0));
                }
            }
            Op::Cut => hop.proxy.cut(),
            Op::Heal => hop.proxy.heal(),
            Op::Restart => hop.restart_gateway(),
            Op::Takeover => {
                let (te, _unused) = poll_lane();
                // Refused while the link is cut: nothing to take over with.
                if let Ok(t) = TradeLeaseBuilder::new(hop.link(), account("prop-taker"), te)
                    .with_timings(fast_trade_timings())
                    .with_takeover(true)
                    .open()
                {
                    taker = Some(t);
                }
            }
            Op::AddAccount => {
                // One added account is enough: a second add while the first lease lives is a no-op.
                if added.is_none() {
                    let (ae, _unused) = poll_lane();
                    let mut account = account("prop-added");
                    account.label = Some("ALT".to_string());
                    account.route_key = format!("{}#ALT", hop_rig::VENUE);
                    if let Ok(s) = TradeLeaseBuilder::new(hop.link(), account, ae)
                        .with_timings(fast_trade_timings())
                        .open()
                    {
                        let _ = s.start_adapter(start_args());
                        added = Some(s);
                    }
                }
            }
            Op::RemoveAccount => {
                // The stop's own detach (phase one, then the join): the lease says its goodbye and closes.
                if let Some(a) = added.take() {
                    a.detach();
                }
            }
            Op::Pause => std::thread::sleep(Duration::from_millis(150)),
            Op::VenueEndsUnheard(n) => {
                if !submitted.is_empty() {
                    hop.world.cancel_unheard(&submitted[n % submitted.len()]);
                }
            }
        }
        events_of(&mut lane, &mut got);
    }

    mark("heal; waiting for the lease".to_string());
    // The link comes back; the lease either recovers or has been closed for good.
    hop.proxy.heal();
    if !wait_until(SETTLE, || {
        session.link_state() == TradeLinkState::Up || session.closed_reason().is_some()
    }) {
        return Err(format!("the lease neither recovered nor closed (ops {ops:?})"));
    }
    // A pause that gives the chaos's own events time to land before the sweep; no verdict below rests on it.
    std::thread::sleep(Duration::from_millis(700));
    events_of(&mut lane, &mut got);

    // What the tradehub does after a reconnect: the adapter again (answered from the running one when the
    // daemon did not restart). The answer is also the verdict on the lease.
    let open = start_until_answered(&session)?.is_some();
    if open {
        // And the lookup of what stayed UNKNOWN.
        let unknown = session.unknown_orders();
        if !unknown.is_empty() {
            let _ = session.resolve_orders(&unknown);
        }
        // A pause, as above.
        std::thread::sleep(Duration::from_millis(400));
        events_of(&mut lane, &mut got);
        mark(format!("after reconnect: unknown {:?}", session.unknown_orders()));
        // The sweep: every order the core holds no terminal for and nothing names is cancelled, once. It stays
        // open for the whole wait because a lookup's answer can un-name an order at any moment. An order the
        // venue saw and that is still named has that answer on its way; only one it never saw stays named for good.
        let mut swept = BTreeSet::new();
        wait_until(SETTLE, || {
            events_of(&mut lane, &mut got);
            let named: BTreeSet<String> = session.unknown_orders().into_iter().collect();
            for order_client_id in &submitted {
                if terminals(&got, order_client_id) == 0
                    && !named.contains(order_client_id)
                    && swept.insert(order_client_id)
                {
                    mark(format!("sweep cancels {order_client_id}"));
                    exec.cancel(order_client_id);
                }
            }
            let seen = hop.world.seen_submits();
            submitted
                .iter()
                .all(|c| terminals(&got, c) >= 1 || (named.contains(c) && !seen.contains(c)))
        });
    }
    // Rule 3 says where each submit ENDS UP, so it is waited for and never slept for: the proxy, the dispatch
    // thread and the venue's thread stand between the daemon's acknowledgement and the venue, and the link
    // thread between a takeover's goodbye and the UNKNOWN mark, each starved for as long as the box likes. An
    // order that really vanished never arrives, and fails rule 3 below at the bound.
    wait_until(SETTLE, || {
        events_of(&mut lane, &mut got);
        let seen = hop.world.seen_submits();
        let named = session.unknown_orders();
        submitted.iter().all(|c| seen.contains(c) || rejected(&got, c) || named.contains(c))
    });
    // Late bad news (a second terminal, a phantom) has a moment to show; nothing passes on this pause.
    std::thread::sleep(Duration::from_millis(200));
    events_of(&mut lane, &mut got);

    let seen: BTreeSet<String> = hop.world.seen_submits().into_iter().collect();
    let unknown: BTreeSet<String> = session.unknown_orders().into_iter().collect();
    let mut problems = Vec::new();
    for order_client_id in &submitted {
        let ends = terminals(&got, order_client_id);
        let was_rejected = rejected(&got, order_client_id);
        let saw = seen.contains(order_client_id);
        let live_ends = live_terminals(&got, order_client_id);
        let again = restated_terminals(&got, order_client_id);
        if live_ends > 1 {
            problems.push(format!("{order_client_id}: {live_ends} live terminal events (rule 1)"));
        }
        if again > hop.world.restatements(order_client_id) {
            problems.push(format!(
                "{order_client_id}: {again} re-stated terminals, but the venue's lookup answered {} (rule 1)",
                hop.world.restatements(order_client_id)
            ));
        }
        if was_rejected && saw {
            problems.push(format!(
                "{order_client_id}: rejected, yet the venue holds it: a phantom (rule 2)"
            ));
        }
        if !saw && !was_rejected && !unknown.contains(order_client_id) {
            problems.push(format!(
                "{order_client_id}: never seen, never rejected, not UNKNOWN: vanished (rule 3)"
            ));
        }
        // The ONE pending order rule 4 leaves to reconcile: the venue ended it (its cancel ran as the daemon
        // died, so the ending event went nowhere) and says so now ("unknown order"). The client was told
        // `Accepted`, so it is no UNKNOWN submit, and a lost cancel's outcome is reconcile's by design
        // (`vike-gatewayhub-client`'s `trade/ledger.rs` module doc). Only across a daemon restart: inside
        // one epoch a lost ending is a defect.
        let left_to_reconcile = saw
            && session.stats().epoch_changes > 0
            && !hop.world.resting().contains(order_client_id)
            && cancel_refused(&got, order_client_id);
        if open && ends == 0 && !unknown.contains(order_client_id) && !left_to_reconcile {
            problems.push(format!("{order_client_id}: still pending after the sweep (rule 4)"));
        }
    }
    let diag = format!(
        "trace:\n{}\nclient stats {:?}\nlease closed {:?}\nresolutions {:?}\nevents {:?}\ndaemon-side exec calls {:?}\nlane calls {:?}",
        TRACE.with(|t| t.borrow().1.join("\n")),
        session.stats(),
        session.closed_reason(),
        submitted.iter().map(|c| (c.clone(), session.resolution_of(c))).collect::<Vec<_>>(),
        got.iter()
            .filter(|e| order_client_id_of(e).is_some_and(|c| submitted.iter().any(|s| s == c)))
            .map(|e| format!("{e:?}"))
            .collect::<Vec<_>>(),
        hop.lane.calls(),
        hop.lane.inner.calls(),
    );
    session.detach();
    if let Some(t) = taker {
        t.detach();
    }
    if let Some(a) = added {
        a.detach();
    }
    if problems.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "ops {ops:?}
submitted {submitted:?}
venue saw {seen:?}
unknown {unknown:?}
lease open {open}
{}
{diag}",
            problems.join("\n")
        ))
    }
}

